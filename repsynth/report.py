"""Reporting (H12, PRV-04, PRV-06): RESUME.md and the status page, generated from status files and
run records. Never edited by hand. A packet with no status file is reported as not built."""
from __future__ import annotations

import csv
import html
import json
from pathlib import Path

from . import NOTICE, __version__
from .records import ROOT

PLAN = ROOT / "plan"


def _packets(root: Path, repo: str = "hmnsq/repsynth"):
    with open(root / "plan" / "packets.csv", encoding="utf-8") as f:
        rows = [r for r in csv.DictReader(f) if not r["id"].startswith("#")]
    return [r for r in rows if r["repository"].startswith(repo)]


def _status(root: Path) -> dict:
    out = {}
    for p in sorted((root / "reports" / "status").glob("*.json")):
        try:
            d = json.loads(p.read_text(encoding="utf-8"))
            out[d["packet"]] = d
        except Exception as e:  # shown, not hidden
            out[p.stem] = {"packet": p.stem, "state": "failed", "summary": f"unreadable status file: {e}", "evidence": []}
    return out


def _iterations(root: Path) -> list[dict]:
    with open(root / "plan" / "iterations.csv", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def resume_text(root: Path = ROOT) -> str:
    st = _status(root)
    pk = _packets(root)
    counts = {}
    lines = ["# RESUME", "", "Generated by `repsynth report` from reports/status and records/. Never edited by hand.", "",
             NOTICE.replace("\n", "  \n"), "", f"repsynth {__version__}", ""]
    rows = []
    for r in pk:
        s = st.get(r["id"], {"state": "not_built", "summary": "No status file: nothing has been run for this packet.", "evidence": [], "blocked_by": []})
        counts[s["state"]] = counts.get(s["state"], 0) + 1
        ev = s.get("evidence") or []
        rows.append(f"| {r['id']} | {r['title']} | {s['state']} | {s.get('summary','').replace('|', '/')} | "
                    f"{'<br>'.join(str(e) for e in ev[:3])}{' …' if len(ev) > 3 else ''} | {', '.join(s.get('blocked_by') or [])} |")
    lines.append("## Packet states")
    lines.append("")
    lines.append(", ".join(f"{k}: {v}" for k, v in sorted(counts.items())))
    lines.append("")
    lines += ["| Packet | Title | State | Summary | Evidence | Blocked by |", "|---|---|---|---|---|---|"] + rows
    lines += ["", "States: done means its acceptance command ran here and passed; wired_unproven means code exists but the acceptance has not run or not passed; not_built means nothing was run; failed means the acceptance ran and failed.", ""]
    extra = sorted(set(st) - {r["id"] for r in pk})
    if extra:
        lines += ["## Other status entries", ""] + [f"- {k}: {st[k]['state']}: {st[k].get('summary','')}" for k in extra] + [""]
    return "\n".join(lines)


def status_page(root: Path = ROOT) -> str:
    st = _status(root)
    pk = _packets(root)
    def badge(s):
        return f'<span class="b {s}">{html.escape(s)}</span>'
    trs = []
    for r in pk:
        s = st.get(r["id"], {"state": "not_built", "summary": "No status file."})
        trs.append(f"<tr><td>{r['id']}</td><td>{html.escape(r['title'])}</td><td>{badge(s['state'])}</td><td>{html.escape(s.get('summary',''))}</td></tr>")
    extra = ""
    for name, title in (("reports/baseline/baseline.md", "Binary performance baseline"),
                        ("reports/compatibility.md", "Compatibility matrix"),
                        ("reports/capability.md", "Capability matrix"),
                        ("reports/scripts/status.md", "Script status")):
        p = root / name
        if p.exists():
            extra += f"<h2>{html.escape(title)}</h2><pre>{html.escape(p.read_text(encoding='utf-8')[:20000])}</pre>"
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>repsynth status</title>
<style>
:root{{--bg:#fff;--fg:#1b1b1b;--mut:#5d5d5d;--line:#ddd;--done:#1e7b34;--wired:#946200;--nb:#6b6b6b;--fail:#b3261e}}
@media (prefers-color-scheme:dark){{:root{{--bg:#151515;--fg:#eee;--mut:#aaa;--line:#333;--done:#5bc274;--wired:#e0b04a;--nb:#9a9a9a;--fail:#ff8a80}}}}
body{{background:var(--bg);color:var(--fg);font:15px/1.5 system-ui,sans-serif;margin:0 auto;max-width:1100px;padding:16px}}
table{{border-collapse:collapse;width:100%}}td,th{{border-bottom:1px solid var(--line);padding:6px;text-align:left;vertical-align:top}}
.b{{font-weight:600;white-space:nowrap}}.done{{color:var(--done)}}.wired_unproven{{color:var(--wired)}}.not_built{{color:var(--nb)}}.failed{{color:var(--fail)}}
pre{{overflow-x:auto;font-size:13px}}small{{color:var(--mut)}}
@media (max-width:640px){{td:nth-child(4){{display:none}}}}
</style></head><body>
<h1>repsynth status</h1>
<p><small>{html.escape(NOTICE)}<br>Generated from run records by repsynth {__version__}. Simulated is not built; emulator figures are not hardware speed.</small></p>
<table><thead><tr><th>Packet</th><th>Title</th><th>State</th><th>Summary</th></tr></thead><tbody>
{''.join(trs)}
</tbody></table>
{extra}
</body></html>
"""


def report(root: Path = ROOT) -> int:
    (root / "RESUME.md").write_text(resume_text(root), encoding="utf-8")
    (root / "docs").mkdir(exist_ok=True)
    (root / "docs" / "index.html").write_text(status_page(root), encoding="utf-8")
    print("wrote RESUME.md and docs/index.html")
    return 0
