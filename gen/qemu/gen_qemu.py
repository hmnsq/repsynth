"""QEMU Tier A generator (ISA-05, P4.2): decodetree file, translation functions, helper declarations
and bodies that call the reference functions, the CPU property that guards the extension, and the
build entries, as exact-anchor patches for the pinned QEMU tree (applied by gen/qemu/patch_qemu.py).

Called through repsynth.lanes.graph_tiera (nodes qemu:<sid>:<op> and qemu:<sid>).
Generated files are compiled into QEMU and so carry GPL-2.0-or-later."""
from __future__ import annotations

import json

GENERATOR = "repsynth.gen.qemu 0.3.0"
QEMU_DIR = "target/riscv/xaye"


def _head(ctx, what: str, comment: str = "c") -> str:
    lines = ["© 1993–2026 Abhishek Choudhary. All rights reserved. AyeAI.",
             "SPDX-License-Identifier: GPL-2.0-or-later",
             what,
             f"Generated by {GENERATOR} from {ctx['sid']} {ctx['version']} (active encoding: {ctx['encoding']}).",
             f"slice_sha256: {ctx['slice_sha256']}",
             "Do not edit."]
    if comment == "#":
        return "".join(f"# {l}\n" for l in lines)
    return "/* " + "\n * ".join(lines) + " */\n"


def _widths(ctx):
    return {x["register_bits"]: x["digits"] for x in ctx["widths"]}


def _symbol(op: dict, digits: int) -> str:
    ref = op["reference"]
    pat = ref.get("symbol_pattern") or ref.get("symbol")
    return pat.replace("{width}", str(digits))


def insn_name(ext: str, op: str) -> str:
    return f"{ext}_{op}"


def render_op(ctx: dict, root=None) -> dict:
    op, e, ext, sid = ctx["op"], ctx["entry"], ctx["ext"]["extension"], ctx["sid"]
    name = op["name"]
    w = _widths(ctx)
    unary = op["arity"] == 1
    n = insn_name(ext, name)
    hdecl = (_head(ctx, f"Helper declarations for {e['mnemonic']}.") +
             f"DEF_HELPER_FLAGS_2({n}_r64, TCG_CALL_NO_RWG_SE, tl, tl, tl)\n"
             f"DEF_HELPER_FLAGS_2({n}_r32, TCG_CALL_NO_RWG_SE, tl, tl, tl)\n")
    s64, s32 = _symbol(op, w[64]), _symbol(op, w[32])
    hbody = (_head(ctx, f"Helper bodies for {e['mnemonic']}: each calls the reference function (SPC-03).") +
             f"/* {op['meaning']} */\n"
             f"target_ulong HELPER({n}_r64)(target_ulong a, target_ulong b)\n{{\n"
             f"    return (target_ulong){s64}((uint64_t)a, (uint64_t)b);\n}}\n\n"
             f"target_ulong HELPER({n}_r32)(target_ulong a, target_ulong b)\n{{\n"
             f"    return (target_ulong)(target_long)(int32_t)(uint32_t){s32}((uint32_t)a, (uint32_t)b);\n}}\n")
    src2 = "tcg_constant_tl(0)" if unary else "get_gpr(ctx, a->rs2, EXT_NONE)"
    trans = (_head(ctx, f"Translation of {e['mnemonic']} (match {e['match']}, mask {e['mask']}).") +
             f"static bool trans_{n}(DisasContext *ctx, arg_{n} *a)\n{{\n"
             f"    TCGv dest = dest_gpr(ctx, a->rd);\n"
             f"    TCGv src1 = get_gpr(ctx, a->rs1, EXT_NONE);\n"
             f"    TCGv src2 = {src2};\n\n"
             f"    if (get_xl(ctx) == MXL_RV32) {{\n"
             f"        gen_helper_{n}_r32(dest, src1, src2);\n"
             f"    }} else {{\n"
             f"        gen_helper_{n}_r64(dest, src1, src2);\n"
             f"    }}\n"
             f"    gen_set_gpr(ctx, a->rd, dest);\n"
             f"    return true;\n}}\n")
    b = f"gen/qemu/out/{sid}/ops/{name}"
    return {f"{b}.trans.c.inc": trans, f"{b}.helper.h": hdecl, f"{b}.helper.c.inc": hbody}


def _bits(v: int, n: int) -> str:
    return format(v, f"0{n}b")


def render_spec(ctx: dict, root=None) -> dict:
    sid, extd = ctx["sid"], ctx["ext"]
    ext, prop = extd["extension"], extd["cpu_property"]
    ops = [o for _, o in ctx["ops"]]
    entries = {e["op"]: e for e in ctx["entries"]}
    dec = [_head(ctx, f"Decodetree patterns of {ext} ({extd['opcode_space']}, funct3 {extd['funct3']}).", "#"),
           "%rs2       20:5", "%rs1       15:5", "%rd        7:5", "",
           "&r         rd rs1 rs2   !extern", "&r2        rd rs1       !extern", "",
           "@r         ....... ..... ..... ... ..... ....... &r  %rs2 %rs1 %rd",
           "@r2        ....... ..... ..... ... ..... ....... &r2 %rs1 %rd", ""]
    for o in ops:
        e = entries[o["name"]]
        rs2 = "00000" if e["rs2"] == "zero" else "....."
        fmt = "@r2" if e["rs2"] == "zero" else "@r"
        dec.append(f"{insn_name(ext, o['name']):<20} {_bits(e['funct7'], 7)} {rs2} ..... {_bits(e['funct3'], 3)} "
                   f"..... {_bits(e['opcode'], 7)} {fmt}")
    decode = "\n".join(dec) + "\n"
    trans = (_head(ctx, f"Translation functions of {ext}.") +
             "".join(f"#include \"ops/{o['name']}.trans.c.inc\"\n" for o in ops))
    hdecl = (_head(ctx, f"Helper declarations of {ext}; included from target/riscv/helper.h (no include guard, "
                        "helper.h is read several times).") +
             "".join(f"#include \"ops/{o['name']}.helper.h\"\n" for o in ops))
    ref_h = f"ref/{sid}.h"
    hsrc = (_head(ctx, f"Helpers of {ext}: each calls the reference function compiled from spec/ref/{sid}.") +
            "#include \"qemu/osdep.h\"\n#include \"cpu.h\"\n#include \"exec/helper-proto.h\"\n"
            f"#include \"{ref_h}\"\n\n" +
            "".join(f"#include \"ops/{o['name']}.helper.c.inc\"\n" for o in ops))
    d = f"{QEMU_DIR}/{sid}"
    patches = {
        "_notice": "© 1993–2026 Abhishek Choudhary. All rights reserved. AyeAI. SPDX-License-Identifier: CC0-1.0",
        "generator": GENERATOR, "spec": sid, "version": ctx["version"], "slice_sha256": ctx["slice_sha256"],
        "extension": ext, "cpu_property": prop,
        "copy": [{"from": f"gen/qemu/out/{sid}", "to": d, "pattern": "**/*", "exclude": ["patches.json"]},
                 {"from": f"spec/ref/{sid}", "to": f"{d}/ref", "pattern": "*.[ch]"}],
        "anchors": [
            {"file": "target/riscv/meson.build", "where": "after",
             "anchor": "  decodetree.process('XVentanaCondOps.decode', extra_args: '--static-decode=decode_XVentanaCodeOps'),\n",
             "text": f"  decodetree.process('xaye/{sid}/{ext}.decode', extra_args: '--static-decode=decode_{ext}'),\n"},
            {"file": "target/riscv/meson.build", "where": "before", "anchor": "  'vcrypto_helper.c'\n))\n",
             "text": f"  'xaye/{sid}/{ext}_helper.c',\n  'xaye/{sid}/ref/{sid}.c',\n"},
            {"file": "target/riscv/cpu_cfg_fields.h.inc", "where": "after", "anchor": "BOOL_FIELD(ext_XVentanaCondOps)\n",
             "text": f"BOOL_FIELD(ext_{ext})\n"},
            {"file": "target/riscv/cpu_cfg.h", "where": "after", "anchor": "MATERIALISE_EXT_PREDICATE(XVentanaCondOps)\n",
             "text": f"MATERIALISE_EXT_PREDICATE({ext})\n"},
            {"file": "target/riscv/cpu.c", "where": "after",
             "anchor": "const RISCVCPUMultiExtConfig riscv_cpu_experimental_exts[] = {\n",
             "text": f"    MULTI_EXT_CFG_BOOL(\"{prop}\", ext_{ext}, false),\n"},
            {"file": "target/riscv/helper.h", "where": "after",
             "anchor": "DEF_HELPER_FLAGS_3(sc_probe_write, TCG_CALL_NO_WG, void, env, tl, tl)\n",
             "text": f"#include \"xaye/{sid}/helper_{ext}.h\"\n"},
            {"file": "target/riscv/translate.c", "where": "after",
             "anchor": "#include \"insn_trans/trans_xventanacondops.c.inc\"\n",
             "text": f"#include \"decode-{ext}.c.inc\"\n#include \"xaye/{sid}/trans_{ext}.c.inc\"\n"},
            {"file": "target/riscv/translate.c", "where": "after",
             "anchor": "    { has_XVentanaCondOps_p, decode_XVentanaCodeOps},\n",
             "text": f"    { '{' } has_{ext}_p, decode_{ext} {'}'},\n"},
        ],
    }
    b = f"gen/qemu/out/{sid}"
    return {f"{b}/{ext}.decode": decode, f"{b}/trans_{ext}.c.inc": trans, f"{b}/helper_{ext}.h": hdecl,
            f"{b}/{ext}_helper.c": hsrc,
            f"{b}/patches.json": json.dumps(patches, indent=2, ensure_ascii=False) + "\n"}
