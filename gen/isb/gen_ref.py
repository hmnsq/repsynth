"""Reference functions of each machine instance (P7.1, SPC-03).

  python3 gen/isb/gen_ref.py [--check] [NAME ...]

Writes spec/ref/machine_<name>/<name>.h and .c: restricted C11, the uniform signature
uint64_t f(uint64_t a, uint64_t b). The ALU functions call the numeric specification's reference
functions unchanged; the machine functions (imm, ea, val, word, branches) are written in terms of the
numeric specification's own conversion and comparison functions where it has them, and as identities on
two's complement where its words are two's complement integers already.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import isa  # noqa: E402


def _head(m: dict) -> str:
    return (f"/* {isa.NOTICE}\n * SPDX-License-Identifier: GPL-3.0-or-later\n"
            f" * Generated by repsynth.gen.isb.gen_ref {isa.GENERATOR_VERSION} from {m['name']} "
            f"(family sha256 {m['family_sha256'][:16]}, {m['numeric']['identity']['id']} sha256 "
            f"{m['numeric_sha256'][:16]}). Do not edit. */\n")


def render(name: str, root: Path = isa.ROOT) -> dict:
    m = isa.derive(name, root)
    nid = m["numeric"]["identity"]["id"]
    ops = {o["name"] for o in m["numeric"]["operations"]}
    guard = f"MACHINE_{name.upper()}_H"
    h = _head(m) + f"#ifndef {guard}\n#define {guard}\n#include <stdint.h>\n"
    h += "".join(f"uint64_t {isa.sym(m, f['name'])}(uint64_t a, uint64_t b);\n" for f in m["functions"])
    h += f"#endif\n"
    # val and word: the numeric specification's conversions when it has them, else the identity
    # (its words are two's complement integers of the register width).
    if {"to_int", "from_int"} <= ops:
        val = f"{isa.num_sym(m, 'to_int')}(a, 0)"
        word = f"{isa.num_sym(m, 'from_int')}(a, 0)"
        conv = f"{nid} to_int and from_int"
    else:
        if m["digits"] != m["register_bits"]:
            raise ValueError(f"{name}: {nid} has no conversions and its words do not fill the register")
        val, word, conv = "a", "a", "identity (two's complement words)"
    c = _head(m) + f"#include \"{name}.h\"\n#include \"{nid}.h\"\n\n"
    c += f"/* ALU: the {nid} reference functions, unchanged. */\n"
    for f in m["functions"]:
        if f["kind"] == "alu":
            c += (f"uint64_t {isa.sym(m, f['name'])}(uint64_t a, uint64_t b)\n"
                  f"{{ return {isa.num_sym(m, f['name'])}(a, b); }}\n")
    c += f"\n/* Machine functions; val and word use {conv}. */\n"
    lt = f"({isa.num_sym(m, 'cmp')}(a, b) == ~(uint64_t)0)"
    bodies = {
        "imm": f"(void)b; return {word};",
        "ea": f"return {isa.sym(m, 'val')}(a, 0) + b;",
        "val": f"(void)b; return {val};",
        "word": f"(void)b; return {word};",
        "beq": "return a == b ? 1u : 0u;",
        "bne": "return a != b ? 1u : 0u;",
        "blt": f"return {lt} ? 1u : 0u;",
        "bge": f"return {lt} ? 0u : 1u;",
    }
    for f in m["functions"]:
        if f["kind"] == "machine":
            c += f"uint64_t {isa.sym(m, f['name'])}(uint64_t a, uint64_t b)\n{{ {bodies[f['name']]} }}\n"
    d = isa.ref_dir(name)
    return {f"{d}/{name}.h": h, f"{d}/{name}.c": c}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--root", default=str(isa.ROOT))
    ap.add_argument("names", nargs="*")
    a = ap.parse_args(argv)
    bad = 0
    root = Path(a.root)
    for n in a.names or list(isa.instances(root)):
        for rel, text in render(n, root).items():
            p = root / rel
            if a.check:
                if not p.exists() or p.read_text(encoding="utf-8") != text:
                    print(f"DIFFERS {rel}")
                    bad = 1
            elif not p.exists() or p.read_text(encoding="utf-8") != text:
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_text(text, encoding="utf-8")
                print(f"wrote {rel}")
    return bad


if __name__ == "__main__":
    sys.exit(main())
