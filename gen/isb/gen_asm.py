"""customasm instruction definitions generated from each machine specification (P7.3, ISB-02).

  python3 gen/isb/gen_asm.py [--check] [NAME ...]

Writes gen/isb/targets/<name>/<name>.cpu.asm (a #subruledef for registers, a #ruledef with one rule per
instruction of the specification's encoding table, and the memory bank of the family's memory map) and
gen/isb/targets/<name>/roundtrip.asm with its expected words roundtrip.expect (the encoding round trip).
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import isa  # noqa: E402


def _field_expr(fmt: dict, f: str, var: str) -> str:
    hi, lo, _ = isa.field_spec(fmt, f)
    return f"{var}`{hi - lo + 1}"


def rules(m: dict) -> list[str]:
    out = []
    for ins in m["instructions"]:
        fmt = m["formats"][ins["format"]]
        op = f"{ins['opcode']}`6"
        name = ins["name"]
        f = ins["format"]
        zero = lambda k: f"0`{fmt['zero'][0] - fmt['zero'][1] + 1}"  # noqa: E731
        if f == "R":
            out.append(f"    {name} {{rd: reg}}, {{ra: reg}}, {{rb: reg}} => $le({op} @ rd @ ra @ rb @ {zero('zero')})")
        elif f == "U":
            out.append(f"    {name} {{rd: reg}}, {{ra: reg}} => $le({op} @ rd @ ra @ {zero('zero')})")
        elif f == "I":
            w = fmt["imm"][0] - fmt["imm"][1] + 1
            if name == "jalr":
                out.append(f"    {name} {{rd: reg}}, {{imm: s{w}}}({{ra: reg}}) => $le({op} @ rd @ ra @ imm`{w})")
            else:
                out.append(f"    {name} {{rd: reg}}, {{imm: s{w}}}({{ra: reg}}) => $le({op} @ rd @ ra @ imm`{w})")
        elif f == "B":
            w = fmt["imm"][0] - fmt["imm"][1] + 1
            out.append(f"    {name} {{ra: reg}}, {{rb: reg}}, {{target}} => {{\n"
                       f"        $assert((target - $) % 4 == 0, \"branch target not aligned\")\n"
                       f"        off = (target - $) / 4\n"
                       f"        $assert(off >= -(1 << {w - 1}) && off < (1 << {w - 1}), \"branch out of range\")\n"
                       f"        $le({op} @ ra @ rb @ off`{w})\n    }}")
        elif f == "J":
            w = fmt["imm"][0] - fmt["imm"][1] + 1
            if name == "jal":
                out.append(f"    {name} {{rd: reg}}, {{target}} => {{\n"
                           f"        $assert((target - $) % 4 == 0, \"jump target not aligned\")\n"
                           f"        off = (target - $) / 4\n"
                           f"        $assert(off >= -(1 << {w - 1}) && off < (1 << {w - 1}), \"jump out of range\")\n"
                           f"        $le({op} @ rd @ off`{w})\n    }}")
            else:
                out.append(f"    {name} {{rd: reg}}, {{imm: s{w}}} => $le({op} @ rd @ imm`{w})")
        else:
            raise ValueError(f"format {f} has no customasm rule")
    return out


def render(name: str, root: Path = isa.ROOT) -> dict:
    m = isa.derive(name, root)
    ram = m["memory_map"]["ram"]
    head = (f"; {isa.NOTICE}\n; SPDX-License-Identifier: GPL-3.0-or-later\n"
            f"; customasm instruction definition of {name}, generated by repsynth.gen.isb.gen_asm "
            f"{isa.GENERATOR_VERSION} from {isa.instance_path(name)} (family sha256 {m['family_sha256'][:16]}). Do not edit.\n")
    cpu = head + ("#subruledef reg\n{\n    r{n: u4} => n`4\n}\n\n#ruledef\n{\n" + "\n".join(rules(m)) + "\n}\n\n"
                  f"#bankdef ram {{ #addr {ram['base']:#x}, #size {ram['size']:#x}, #outp 0 }}\n")
    # round trip: every instruction over chosen operands
    lines, words = [], []
    pc = 0
    for ins in m["instructions"]:
        fmt = m["formats"][ins["format"]]
        for k, regs in enumerate([(0, 0, 0), (1, 2, 3), (15, 14, 13), (7, 8, 9)]):
            rd, ra, rb = regs
            n = ins["name"]
            f = ins["format"]
            if f == "R":
                fields, text = {"rd": rd, "ra": ra, "rb": rb}, f"{n} r{rd}, r{ra}, r{rb}"
            elif f == "U":
                fields, text = {"rd": rd, "ra": ra}, f"{n} r{rd}, r{ra}"
            elif f == "I":
                hi, lo, _ = isa.field_spec(fmt, "imm")
                imm = [0, -8, (1 << (hi - lo)) - 1, -(1 << (hi - lo))][k]
                fields, text = {"rd": rd, "ra": ra, "imm": imm}, f"{n} r{rd}, {imm}(r{ra})"
            elif f == "B":
                off = [0, -1, 3, -(pc // 4)][k]
                fields, text = {"ra": ra, "rb": rb, "imm": off}, f"{n} r{ra}, r{rb}, {pc + 4 * off:#x}"
            elif n == "jal":
                off = [0, 1, -2, 5][k] if pc >= 8 else [0, 1, 2, 5][k]
                fields, text = {"rd": rd, "imm": off}, f"{n} r{rd}, {pc + 4 * off:#x}"
            else:
                hi, lo, _ = isa.field_spec(fmt, "imm")
                imm = [0, -1, (1 << (hi - lo)) - 1, -(1 << (hi - lo))][k]
                fields, text = {"rd": rd, "imm": imm}, f"{n} r{rd}, {imm}"
            lines.append(f"    {text}")
            words.append(f"{isa.encode(m, n, **fields):08x} {n} " + " ".join(f"{a}={b}" for a, b in sorted(fields.items())))
            pc += 4
    rt = head.replace("instruction definition of", "encoding round-trip source of") + f"#include \"{name}.cpu.asm\"\n#bank ram\n" + "\n".join(lines) + "\n"
    expect = "\n".join(words) + "\n"
    d = f"gen/isb/targets/{name}"
    return {f"{d}/{name}.cpu.asm": cpu, f"{d}/roundtrip.asm": rt, f"{d}/roundtrip.expect": expect}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--root", default=str(isa.ROOT))
    ap.add_argument("names", nargs="*")
    a = ap.parse_args(argv)
    root = Path(a.root)
    bad = 0
    for n in a.names or list(isa.instances(root)):
        for rel, text in render(n, root).items():
            p = root / rel
            if a.check:
                if not p.exists() or p.read_text(encoding="utf-8") != text:
                    print(f"DIFFERS {rel}")
                    bad = 1
            elif not p.exists() or p.read_text(encoding="utf-8") != text:
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_text(text, encoding="utf-8")
                print(f"wrote {rel}")
    return bad


if __name__ == "__main__":
    sys.exit(main())
