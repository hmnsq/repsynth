def render(root: Path = isa.ROOT) -> dict:
    names = list(isa.instances(root))
    files, copies = {}, []
    models = [isa.derive(n, root) for n in names]
    for m in models:
        n = m["name"]
        for rel, text in files_for(m).items():
            files[f"gen/isb/targets/{n}/qemu/{rel}"] = text
        copies.append({"from": f"gen/isb/targets/{n}/qemu", "to": ".", "pattern": "**/*"})
        nid = m["numeric"]["identity"]["id"]
        copies.append({"from": isa.ref_dir(n), "to": f"target/{n}/ref", "pattern": "*.[ch]"})
        copies.append({"from": f"spec/ref/{nid}", "to": f"target/{n}/ref", "pattern": "*.[ch]"})
    sub = "".join(f"subdir('{n}')\n" for n in names)
    src = "".join(f"source {n}/Kconfig\n" for n in names)
    arch = "".join(f"    QEMU_ARCH_{n.upper()} = (1 << {ARCH_BITS[n]}),\n" for n in names)
    enum = "".join(f"'{n}', " for n in names)
    patches = {
        "_notice": f"{isa.NOTICE} SPDX-License-Identifier: CC0-1.0",
        "generator": f"repsynth.gen.isb.gen_qemu {isa.GENERATOR_VERSION}",
        "qemu": QEMU_TAG,
        "specs": {m["name"]: {"family_sha256": m["family_sha256"], "numeric_sha256": m["numeric_sha256"]} for m in models},
        "anchors": [
            {"file": "target/meson.build", "anchor": "subdir('avr')\n", "where": "after", "text": sub},
            {"file": "target/Kconfig", "anchor": "source avr/Kconfig\n", "where": "after", "text": src},
            {"file": "hw/meson.build", "anchor": "subdir('avr')\n", "where": "after", "text": sub},
            {"file": "hw/Kconfig", "anchor": "source avr/Kconfig\n", "where": "after", "text": src},
            {"file": "include/system/arch_init.h", "anchor": "    QEMU_ARCH_LOONGARCH = (1 << 23),\n", "where": "after", "text": arch},
            {"file": "qapi/machine.json", "anchor": "  'data' : [ 'aarch64', 'alpha', 'arm', 'avr', ", "where": "after", "text": enum},
        ],
        "copy": copies,
    }
    files["gen/isb/targets/qemu_patches.json"] = json.dumps(patches, indent=2, ensure_ascii=False) + "\n"
    return files


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--root", default=str(isa.ROOT))
    a = ap.parse_args(argv)
    root = Path(a.root)
    bad = 0
    for rel, text in render(root).items():
        p = root / rel
        if a.check:
            if not p.exists() or p.read_text(encoding="utf-8") != text:
                print(f"DIFFERS {rel}")
                bad = 1
        elif not p.exists() or p.read_text(encoding="utf-8") != text:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text, encoding="utf-8")
            print(f"wrote {rel}")
    return bad


if __name__ == "__main__":
    sys.exit(main())
