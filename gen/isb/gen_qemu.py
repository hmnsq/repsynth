"""QEMU target generator for the word machine family (P7.2, ISB-01).

  python3 gen/isb/gen_qemu.py [--check]

For each instance writes gen/isb/targets/<name>/qemu/, a tree that mirrors the pinned QEMU source:
target/<name>/ (cpu.h, cpu-qom.h, cpu-param.h, cpu.c, translate.c, insn.decode, helper.h, op_helper.c,
meson.build, Kconfig), hw/<name>/ (board.c with RAM, a 16550 UART and the sifive_test finisher, meson.build,
Kconfig) and configs/. Writes gen/isb/targets/qemu_patches.json: the copies of those trees and of the
reference sources into a derived QEMU tree, and exact-anchor insertions into the pinned tree's shared files
(target and hw meson.build and Kconfig, qapi/machine.json, include/system/arch_init.h).

The decodetree file comes from the specification's encoding table; every data effect of an instruction is
a helper that calls the instance's reference function (constants are folded at translation time by calling
the same reference function). Written against QEMU v10.2.4: target/avr, target/tricore and
docs/devel/decodetree.rst of that tree were read for the interfaces used here.
"""
