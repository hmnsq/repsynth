def decode_file(m: dict) -> str:
    fm = m["formats"]
    lines = [_hash_head(m, f"Decodetree description of {m['name']}, from /encoding/encodings/fixed32."), ""]
    args = {"R": "&r rd ra rb", "U": "&u rd ra", "I": "&i rd ra imm", "B": "&b ra rb imm", "J": "&j rd imm"}
    for f in fm:
        lines.append(args[f])
    lines.append("")
    for f, fields in fm.items():
        parts = []
        for name, spec in sorted(fields.items(), key=lambda kv: -kv[1][0]):
            hi, lo, signed = isa.field_spec(fields, name)
            w = hi - lo + 1
            if name in ("op", "zero"):
                parts.append("." * w)
            else:
                parts.append(f"{name}:{'s' if signed else ''}{w}")
        lines.append(f"@{f.lower()} " + " ".join(parts) + f" &{f.lower()}")
    lines.append("")
    for ins in m["instructions"]:
        fields = fm[ins["format"]]
        parts = []
        for name, spec in sorted(fields.items(), key=lambda kv: -kv[1][0]):
            hi, lo, _ = isa.field_spec(fields, name)
            w = hi - lo + 1
            if name == "op":
                parts.append(format(ins["opcode"], f"0{w}b"))
            elif name == "zero":
                parts.append("0" * w)
            else:
                parts.append("." * w)
        lines.append(f"{ins['name']:<9} " + " ".join(parts) + f" @{ins['format'].lower()}")
    return "\n".join(lines) + "\n"


