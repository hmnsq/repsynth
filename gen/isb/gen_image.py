"""Bare-metal test image sources for each machine (P7.3, P7.4).

  python3 gen/isb/gen_image.py [--check] [--max-cases N] [NAME ...]

Writes .cache/isb/images/<name>/vectors.asm (large: every vector case is embedded, so it is kept out of the
tree and regenerated deterministically; records carry its sha256). The image first checks the machine instructions
(loads and stores, byte access, the four branches, jal and jalr), then, for every ALU operation of the
specification, runs every case of the shared vector file conformance/vectors/<numeric>/<op>.<digits>.vec
embedded raw in the image data and compares the host bits of the result with the expected field. It
prints "ok <op> <cases>" on the UART per operation and "PASS" at the end and exits 0 through the finisher;
on the first mismatch it prints "FAIL <op>" and exits 1; a machine-instruction failure exits 2.

Constants that the machine reads as numbers (device addresses) are stored as words of the instance's
representation, computed here with the numeric specification's independent Python oracle; every other
number is a small immediate turned into a word by the machine's own li.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import isa  # noqa: E402

sys.path.insert(0, str(isa.ROOT))
from repsynth.numeric import read_vectors  # noqa: E402


def word_of(m: dict, x: int) -> int:
    nid = m["numeric"]["identity"]["id"]
    if nid == "balanced_ternary":
        from repsynth.oracles_num.balanced_ternary import BT
        return BT(m["numeric"], m["digits"]).word(x)
    return x & ((1 << m["register_bits"]) - 1)


def _bytes(s: str) -> str:
    return "#d8 " + ", ".join(f"{b:#04x}" for b in (s.encode() + b"\0"))


def render(name: str, root: Path = isa.ROOT, max_cases: int | None = None) -> dict:
    m = isa.derive(name, root)
    nid = m["numeric"]["identity"]["id"]
    mm = m["memory_map"]
    L = []
    D = []
    a = L.append
    a(f"; {isa.NOTICE}\n; SPDX-License-Identifier: GPL-3.0-or-later")
    a(f"; Vector test image of {name}, generated by repsynth.gen.isb.gen_image {isa.GENERATOR_VERSION} from "
      f"{isa.instance_path(name)} and conformance/vectors/{nid}. Do not edit.")
    a(f"; assembled after gen/isb/targets/{name}/{name}.cpu.asm (customasm takes both files in that order)\n#bank ram\n")
    a("start:")
    a("    ld r13, uart_addr(r0)\n    ld r12, exit_addr(r0)\n    li r3, 1")
    # machine instruction checks
    a("; machine instructions")
    a("    li r5, -5\n    li r6, 7")
    a("    blt r5, r6, m1\n    jal r0, fail_machine\nm1:")
    a("    bge r6, r5, m2\n    jal r0, fail_machine\nm2:")
    a("    bge r5, r6, fail_machine\n    blt r6, r5, fail_machine")
    a("    bge r6, r6, m3\n    jal r0, fail_machine\nm3:")
    a("    beq r5, r5, m4\n    jal r0, fail_machine\nm4:")
    a("    bne r5, r6, m5\n    jal r0, fail_machine\nm5:")
    a("    beq r5, r6, fail_machine\n    bne r6, r6, fail_machine")
    a("    st r5, scratch(r0)\n    ld r7, scratch(r0)\n    bne r5, r7, fail_machine")
    a("    sb r6, scratch+8(r0)\n    lb r7, scratch+8(r0)\n    bne r6, r7, fail_machine")
    a("    sw r5, scratch+16(r0)\n    lb r7, scratch+16(r0)\n    li r8, 251\n    bne r7, r8, fail_machine")
    a("    jal r15, m_sub\n    jal r0, fail_machine\nm_sub:\n    li r8, m6\n    jalr r0, 0(r8)\n    jal r0, fail_machine\nm6:")
    a("    jal r15, m_call\n    jal r0, m7\nm_call:\n    jalr r0, 0(r15)\nm7:")
    a("    li r0, 99\n    bne r0, r0, fail_machine\n    li r8, 0\n    bne r0, r8, fail_machine")
    a("    li r9, msg_machine\n    jal r15, print")
    for op in m["numeric"]["operations"]:
        o = op["name"]
        vec = root / f"conformance/vectors/{nid}/{o}.{m['digits']}.vec"
        head, rows = read_vectors(vec)
        if max_cases:
            rows = rows[:max_cases]
        unary = op["arity"] == 1
        stride = 16 if unary else 24
        a(f"; operation {o}: {len(rows)} cases of {vec.relative_to(root)} (spec_sha256/slice {head.get('slice_sha256', head.get('spec_sha256', '?'))[:16]})")
        a(f"    li r1, cases_{o}\n    li r2, {len(rows)}\n    li r4, {stride}")
        a(f"loop_{o}:\n    beq r2, r0, done_{o}\n    ld r5, 0(r1)")
        if unary:
            a(f"    ld r7, 8(r1)\n    {o} r8, r5")
        else:
            a(f"    ld r6, 8(r1)\n    ld r7, 16(r1)\n    {o} r8, r5, r6")
        a(f"    bne r8, r7, fail_{o}\n    add r1, r1, r4\n    sub r2, r2, r3\n    jal r0, loop_{o}")
        a(f"fail_{o}:\n    li r9, msg_fail_{o}\n    jal r15, print\n    li r10, {0x3333 + (1 << 16)}\n    sw r10, 0(r12)\n    jal r0, hang")
        a(f"done_{o}:\n    li r9, msg_ok_{o}\n    jal r15, print")
        D.append(f"msg_ok_{o}:\n    {_bytes(f'ok {o} {len(rows)}' + chr(10))}")
        D.append(f"msg_fail_{o}:\n    {_bytes(f'FAIL {o}' + chr(10))}")
        D.append(f"    #align 64\ncases_{o}:")
        for r in rows:
            D.append("    #d64 " + ", ".join(f"$le({v:#018x})" for v in r))
    a("    li r9, msg_pass\n    jal r15, print\n    li r10, 0x5555\n    sw r10, 0(r12)\nhang:\n    jal r0, hang")
    a("fail_machine:\n    li r9, msg_fail_machine\n    jal r15, print\n    li r10, " + f"{0x3333 + (2 << 16)}" +
      "\n    sw r10, 0(r12)\n    jal r0, hang")
    a("; print the zero-terminated string at r9 on the UART; returns through r15")
    a("print:\n    lb r10, 0(r9)\n    beq r10, r0, print_end\n    sb r10, 0(r13)\n    add r9, r9, r3\n    jal r0, print\n"
      "print_end:\n    jalr r0, 0(r15)")
    a("    #align 64")
    a(f"uart_addr:\n    #d64 $le({word_of(m, mm['uart']['base']):#018x})")
    a(f"exit_addr:\n    #d64 $le({word_of(m, mm['exit']['base']):#018x})")
    a("scratch:\n    #d64 0, 0, 0")
    a(f"msg_machine:\n    {_bytes('ok machine' + chr(10))}")
    a(f"msg_pass:\n    {_bytes('PASS' + chr(10))}")
    a(f"msg_fail_machine:\n    {_bytes('FAIL machine' + chr(10))}")
    text = "\n".join(L + D) + "\n"
    return {f".cache/isb/images/{name}/vectors.asm": text}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--root", default=str(isa.ROOT))
    ap.add_argument("--max-cases", type=int)
    ap.add_argument("names", nargs="*")
    a = ap.parse_args(argv)
    root = Path(a.root)
    bad = 0
    for n in a.names or list(isa.instances(root)):
        for rel, text in render(n, root, a.max_cases).items():
            p = root / rel
            if a.check:
                if not p.exists() or p.read_text(encoding="utf-8") != text:
                    print(f"DIFFERS {rel}")
                    bad = 1
            elif not p.exists() or p.read_text(encoding="utf-8") != text:
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_text(text, encoding="utf-8")
                print(f"wrote {rel}")
    return bad


if __name__ == "__main__":
    sys.exit(main())
