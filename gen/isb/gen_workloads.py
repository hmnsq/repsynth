"""CMS-03 fixed-point workloads for the binary word machine (P7.4, NUM-06; counts reported, never gated).

  python3 gen/isb/gen_workloads.py [--check]

Writes gen/isb/targets/bwm/workloads/cms03_decay.asm and cms03_oscillator.asm: the same Q2.29 computations
as lanes/toolchain/baseline/cms03_decay.c and cms03_oscillator.c of the RV64 baseline (RK4 decay, 1280
steps; symplectic Euler oscillator, 1608 steps), written for the machine's instruction set. The machine has
no bitwise instructions (its arithmetic is exactly binary_integer's: neg, add, sub, mul, cmp, shl, shr), so
the XOR checksum of the C programs is not computed; each program prints its final state in the same
hexadecimal form ("decay y=XXXXXXXX", "oscillator x=XXXXXXXX v=XXXXXXXX") and the runner compares it with
the RV64 baseline's output. Instruction counts therefore cover the kernel and the printing, not the
checksum, and are reported beside RV64 as a different program of the same computation.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import isa  # noqa: E402

Q = 29


def _bytes(s: str) -> str:
    return "#d8 " + ", ".join(f"{b:#04x}" for b in (s.encode() + b"\0"))


COMMON_HEAD = """; {notice}
; SPDX-License-Identifier: GPL-3.0-or-later
; {what}, generated by repsynth.gen.isb.gen_workloads {ver} for bwm. Do not edit.
; assembled after gen/isb/targets/bwm/bwm.cpu.asm
#bank ram
start:
    ld r13, uart_addr(r0)
    ld r12, exit_addr(r0)
    li r5, 1
    li r10, 28
    shl r6, r5, r10        ; r6 = 2^28, rounding term of qmul
    li r7, 29              ; r7 = Q
"""

COMMON_TAIL = """    #align 32
; print the zero-terminated string at r9; uses r10, r11; returns through r15
print:
    lb r10, 0(r9)
    beq r10, r0, print_end
    sb r10, 0(r13)
    add r9, r9, r5
    jal r0, print
print_end:
    jalr r0, 0(r15)
; print r9 as 8 hexadecimal digits of its low 32 bits (two's complement); uses r10, r11, r14; returns through r15
hex32:
    bge r9, r0, hex_pos
    li r10, 32
    shl r10, r5, r10
    add r9, r9, r10
hex_pos:
    li r14, 28
hex_loop:
    shr r10, r9, r14       ; x >> 4i
    li r11, 4
    add r11, r14, r11
    shr r11, r9, r11       ; x >> 4(i+1)
    li r8, 4
    shl r11, r11, r8
    sub r10, r10, r11      ; nibble
    li r11, 10
    blt r10, r11, hex_digit
    li r11, 87             ; 'a' - 10
    jal r0, hex_out
hex_digit:
    li r11, 48             ; '0'
hex_out:
    add r10, r10, r11
    sb r10, 0(r13)
    beq r14, r0, hex_end
    li r11, 4
    sub r14, r14, r11
    jal r0, hex_loop
hex_end:
    jalr r0, 0(r15)
    #align 64
uart_addr:
    #d64 $le({uart:#018x})
exit_addr:
    #d64 $le({exit:#018x})
"""


def decay_model() -> int:
    one = 1 << Q
    qmul = lambda a, b: (a * b + (1 << (Q - 1))) >> Q  # noqa: E731
    h6 = (one + 3 * 256) // (6 * 256)
    y, k = one, one
    for _ in range(1280):
        k1 = -qmul(k, y)
        k2 = -qmul(k, y + (k1 >> 9))
        k3 = -qmul(k, y + (k2 >> 9))
        k4 = -qmul(k, y + (k3 >> 8))
        s = k1 + 2 * k2 + 2 * k3 + k4
        y = y + ((h6 * s + (1 << (Q - 1))) >> Q)
    return y


def osc_model() -> tuple[int, int]:
    one = 1 << Q
    qmul = lambda a, b: (a * b + (1 << (Q - 1))) >> Q  # noqa: E731
    x, v = one, 0
    for _ in range(1608):
        v = v - (qmul(one, x) >> 8)
        x = x + (v >> 8)
    return x, v


def render(root: Path = isa.ROOT) -> dict:
    m = isa.derive("bwm", root)
    mm = m["memory_map"]
    fmt = dict(notice=isa.NOTICE, ver=isa.GENERATOR_VERSION, uart=mm["uart"]["base"], exit=mm["exit"]["base"])
    one_h6 = ((1 << Q) + 3 * 256) // (6 * 256)
    decay = COMMON_HEAD.format(what="CMS-03 exponential decay, RK4, Q2.29, 1280 steps", **fmt) + f"""    shl r2, r5, r7         ; k = ONE
    mov_y:
    shl r1, r5, r7         ; y = ONE
    li r3, {one_h6}        ; h6 = round(h / 6) in Q2.29
    li r4, 1280
    li r8, 9
    li r11, 8
loop:
    beq r4, r0, done
    mul r10, r2, r1        ; k1 = -qmul(k, y)
    add r10, r10, r6
    shr r10, r10, r7
    neg r10, r10
    add r9, r10, r0        ; sum = k1
    shr r14, r10, r8       ; k2 = -qmul(k, y + (k1 >> 9))
    add r14, r1, r14
    mul r10, r2, r14
    add r10, r10, r6
    shr r10, r10, r7
    neg r10, r10
    add r9, r9, r10
    add r9, r9, r10        ; sum += 2 k2
    shr r14, r10, r8       ; k3 = -qmul(k, y + (k2 >> 9))
    add r14, r1, r14
    mul r10, r2, r14
    add r10, r10, r6
    shr r10, r10, r7
    neg r10, r10
    add r9, r9, r10
    add r9, r9, r10        ; sum += 2 k3
    shr r14, r10, r11      ; k4 = -qmul(k, y + (k3 >> 8))
    add r14, r1, r14
    mul r10, r2, r14
    add r10, r10, r6
    shr r10, r10, r7
    neg r10, r10
    add r9, r9, r10        ; sum += k4
    mul r9, r3, r9         ; y += (h6 sum + 2^28) >> 29
    add r9, r9, r6
    shr r9, r9, r7
    add r1, r1, r9
    sub r4, r4, r5
    jal r0, loop
done:
    li r9, msg_y
    jal r15, print
    add r9, r1, r0
    jal r15, hex32
    li r9, msg_nl
    jal r15, print
    li r10, 0x5555
    sw r10, 0(r12)
hang:
    jal r0, hang
msg_y:
    {_bytes('decay y=')}
msg_nl:
    {_bytes(chr(10))}
""" + COMMON_TAIL.format(**fmt)
    decay = decay.replace("    mov_y:\n", "")
    osc = COMMON_HEAD.format(what="CMS-03 harmonic oscillator, symplectic Euler, Q2.29, 1608 steps", **fmt) + f"""    shl r2, r5, r7         ; w2 = ONE
    shl r1, r5, r7         ; x = ONE
    li r3, 0               ; v = 0
    li r4, 1608
    li r8, 8
loop:
    beq r4, r0, done
    mul r10, r2, r1        ; v -= qmul(w2, x) >> 8
    add r10, r10, r6
    shr r10, r10, r7
    shr r10, r10, r8
    sub r3, r3, r10
    shr r10, r3, r8        ; x += v >> 8
    add r1, r1, r10
    sub r4, r4, r5
    jal r0, loop
done:
    li r9, msg_x
    jal r15, print
    add r9, r1, r0
    jal r15, hex32
    li r9, msg_v
    jal r15, print
    add r9, r3, r0
    jal r15, hex32
    li r9, msg_nl
    jal r15, print
    li r10, 0x5555
    sw r10, 0(r12)
hang:
    jal r0, hang
msg_x:
    {_bytes('oscillator x=')}
msg_v:
    {_bytes(' v=')}
msg_nl:
    {_bytes(chr(10))}
""" + COMMON_TAIL.format(**fmt)
    y = decay_model()
    x, v = osc_model()
    expect = (f"cms03_decay decay y={y & 0xffffffff:08x}\n"
              f"cms03_oscillator oscillator x={x & 0xffffffff:08x} v={v & 0xffffffff:08x}\n")
    d = "gen/isb/targets/bwm/workloads"
    return {f"{d}/cms03_decay.asm": decay, f"{d}/cms03_oscillator.asm": osc, f"{d}/expected.txt": expect}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--root", default=str(isa.ROOT))
    a = ap.parse_args(argv)
    root = Path(a.root)
    bad = 0
    for rel, text in render(root).items():
        p = root / rel
        if a.check:
            if not p.exists() or p.read_text(encoding="utf-8") != text:
                print(f"DIFFERS {rel}")
                bad = 1
        elif not p.exists() or p.read_text(encoding="utf-8") != text:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text, encoding="utf-8")
            print(f"wrote {rel}")
    return bad


if __name__ == "__main__":
    sys.exit(main())
