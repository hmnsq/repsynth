"""Derived APCISR builds per script (P6.3), in <root>/.cache/script/derived/<id>/ (GOV-03: the clone is
never touched; its files are exported with git archive and the generated headers replace apcisr.h and
cisr2asc.h in the export only).

native: APCISR's own Makefile, `make -C APCISR all` (Makefile lines 95-104: libapcisr.a, flex filter).
wasm:   wasi-libc 0.0~git20230113 and clang 18: the filter's scanner generated by flex with --noyywrap,
        compiled with acii2csr.c and lanes/script/wasm/libfl_main.c (the main() libfl gives natively).
probe:  lanes/script/apcisr_probe.c linked with the native libapcisr.a (observation driver, P6.4)."""
from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

from . import refs


def _run(cmd, cwd, env=None, timeout=600) -> dict:
    r = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, errors="replace", env=env, timeout=timeout)
    return {"command": " ".join(str(c) for c in cmd), "cwd": str(cwd), "exit_code": r.returncode,
            "stdout_tail": r.stdout[-1500:], "stderr_tail": r.stderr[-1500:]}


def export(root: Path, folder: str, dest: Path) -> dict:
    src = refs.apcisr_src(root)
    before = refs.git_state(src)
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)
    ar = subprocess.run(["git", "-C", str(src), "archive", "HEAD", folder], capture_output=True, check=True)
    subprocess.run(["tar", "-x", "-C", str(dest)], input=ar.stdout, check=True)
    after = refs.git_state(src)
    return {"clone": str(src), "before": before, "after": after, "unchanged": before == after}


def derived_dir(root: Path, sid: str) -> Path:
    return root / ".cache" / "script" / "derived" / sid


def build_native(root: Path, sid: str, header_dir: Path | None) -> dict:
    d = derived_dir(root, sid) / "native"
    rec = {"export": export(root, "APCISR", d)}
    a = d / "APCISR"
    if header_dir is not None:
        for h in ("apcisr.h", "cisr2asc.h"):
            shutil.copyfile(header_dir / h, a / h)
    rec["make"] = _run(["make", "-C", "APCISR", "all"], d)
    probe = d / "apcisr_probe"
    rec["probe"] = _run(["gcc", "-std=gnu99", "-w", f"-I{a}", "-o", str(probe), str(root / "lanes/script/apcisr_probe.c"),
                         str(a / "libapcisr.a")], d) if rec["make"]["exit_code"] == 0 else {"exit_code": None, "skipped": "make failed"}
    rec["outputs"] = {p: str(a / p) for p in ("acii2csr", "libapcisr.a", "acii2csr.o")}
    rec["outputs"]["apcisr_probe"] = str(probe)
    rec["ok"] = rec["make"]["exit_code"] == 0 and rec["probe"].get("exit_code") == 0 and (a / "acii2csr").exists()
    return rec


def build_wasm(root: Path, sid: str, header_dir: Path | None) -> dict:
    d = derived_dir(root, sid) / "wasm"
    rec = {"export": export(root, "APCISR", d)}
    a = d / "APCISR"
    if header_dir is not None:
        for h in ("apcisr.h", "cisr2asc.h"):
            shutil.copyfile(header_dir / h, a / h)
    rec["flex"] = _run(["flex", "-8", "--noyywrap", "-olexyy.c", "acii2csr.lex"], a)
    w = refs.wasi_sysroot(root)
    pf = refs.prefix(root)
    resdir = subprocess.run(["clang", "-print-resource-dir"], capture_output=True, text=True).stdout.strip()
    cmd = ["clang", "--target=wasm32-wasi", f"--sysroot={pf / 'usr'}"]
    if str(pf) != "/":
        cmd += [f"-resource-dir={pf / 'usr/lib/llvm-18/lib/clang/18'}", "-isystem", f"{resdir}/include"]
    cmd += ["-Wall", "-Wno-unused", "-o", "acii2csr.wasm", "lexyy.c", "acii2csr.c", str(root / "lanes/script/wasm/libfl_main.c")]
    rec["clang"] = _run(cmd, a) if rec["flex"]["exit_code"] == 0 else {"exit_code": None, "skipped": "flex failed"}
    rec["outputs"] = {"acii2csr.wasm": str(a / "acii2csr.wasm")}
    rec["ok"] = rec["clang"].get("exit_code") == 0 and (a / "acii2csr.wasm").exists()
    return rec


def build_romenagri(root: Path) -> dict:
    """The author's Unicode to ISCII converter (Romenagri/uni2acii.c), built with Romenagri's own Makefile
    target `unicode` (Romenagri/Makefile lines 224-226), used to feed Devanagari text to APCISR."""
    d = root / ".cache" / "script" / "derived" / "_romenagri"
    rec = {"export": export(root, "Romenagri", d)}
    rec["make"] = _run(["make", "-C", "Romenagri", "unicode"], d)
    rec["outputs"] = {"uni2acii": str(d / "Romenagri" / "uni2acii")}
    rec["ok"] = rec["make"]["exit_code"] == 0
    return rec
