"""APCISR's own table format (hindawiai/chintamani, APCISR/apcisr.h and APCISR/cisr2asc.h).

A grid table is the list `apcisr_chrt[APCISR_LEN]` of grid9 entries {rmn, acii, purna, grid[9]}
(apcisr.h lines 64-70, 72-403) and three glyph tables `cisr_urdha`, `cisr_nimna`, `cisr_madhya` of
{cell value, glyph code} pairs (cisr2asc.h lines 50, 273, 406). The 9-grid indices, the cisr type and
the grid9 type are fixed by acii2csr.c, which indexes grid[_urdha + _matrik] and so on (acii2csr.c
lines 615-640), so they are emitted unchanged (apcisr.h lines 47-70).

The table model consumed here is a plain dict:
  {"id", "spec_sha256", "candidate", "title", "charset",
   "entries": [{"rmn", "acii_hex", "purna", "grid": [9 ints]}, ...],
   "glyph_tables": {"urdha"|"nimna"|"madhya": {"size": int, "pairs": [[value, code], ...]}}}
"""
from __future__ import annotations

import subprocess
from pathlib import Path

from . import GENERATOR_VERSION, NOTICE

ROWS = ("urdha", "nimna", "madhya")   # the order of the tables in cisr2asc.h


def _c_bytes(raw: bytes) -> str:
    """A C string literal for raw bytes. Plain printable ASCII stays readable; otherwise every byte is
    written as \\xHH, so no hexadecimal escape can swallow a following character."""
    if all(0x20 <= b < 0x7f and chr(b) not in '"\\?' for b in raw):
        return '"' + raw.decode("ascii") + '"'
    return '"' + "".join(f"\\x{b:02x}" for b in raw) + '"'


def _c_string(raw: bytes) -> str:
    return _c_bytes(raw)


def _rmn(s: str) -> str:
    return _c_bytes(s.encode("latin-1") if all(ord(c) < 256 for c in s) else s.encode("utf-8"))


def _banner(t: dict, what: str) -> list[str]:
    lines = ["/* " + NOTICE, " * SPDX-License-Identifier: GPL-2.0-or-later",
             f" * {what} for {t['id']}: {t['title']}",
             f" * Generated by {GENERATOR_VERSION} from specification {t['id']} (sha256 {t['spec_sha256']}). Do not edit.",
             f" * Input encoding of the acii strings: {t['charset']}."]
    if t.get("candidate"):
        lines.append(" * CANDIDATE table (GEN-05): a harness output outside the author's canon; adopting it into APCISR is the author's act.")
    lines.append(" * Format: APCISR's own (hindawiai/chintamani APCISR/apcisr.h and APCISR/cisr2asc.h, GPL-2.0-or-later). */")
    return lines


def emit_apcisr_h(t: dict) -> str:
    L = _banner(t, "Grid table (apcisr.h)")
    L += ["", "#ifndef __APCISR_H__", "#define __APCISR_H__", f"#define APCISR_LEN {len(t['entries'])}", "", "",
          "#ifdef __cplusplus", 'extern "C"', "{", "#endif", "",
          "  static int _urdha = 0;", "  static int _madhya = 3;", "  static int _nimna = 6;", "",
          "  static int _matrik = 0;", "  static int _lipik = 1;", "  static int _purak = 2;", "",
          "  typedef struct", "  {", "    char urdha[1024];", "    char madhya[1024];", "    char nimna[1024];",
          "    int curpos;", "  } cisr;", "", "  typedef struct", "  {", "    char *rmn;", "    char *acii;",
          "    int purna;", "    int grid[9];", "  } grid9;", "",
          "  static grid9 apcisr_chrt[APCISR_LEN] = {"]
    for k, e in enumerate(t["entries"]):
        g = [int(x) for x in e["grid"]]
        if len(g) != 9:
            raise ValueError(f"entry {k} ({e['rmn']}): grid has {len(g)} cells, not 9")
        sep = "," if k < len(t["entries"]) - 1 else ""
        comment = f"  /* {e['comment']} */" if e.get("comment") else ""
        L.append(f"    {{{_rmn(e['rmn'])}, {_c_string(bytes.fromhex(e['acii_hex']))}, {int(e['purna'])}, "
                 f"{{{g[0]}, {g[1]}, {g[2]},")
        L.append(f"      {g[3]}, {g[4]}, {g[5]},")
        L.append(f"      {g[6]}, {g[7]}, {g[8]}}}}}{sep}{comment}")
    L += ["  };", "#ifdef __cplusplus", "}", "#endif", "", "#endif", ""]
    return "\n".join(L)


def emit_cisr2asc_h(t: dict) -> str:
    L = _banner(t, "Glyph tables (cisr2asc.h)")
    L += ["", "#ifndef __CISR2ASC_H__", "#define __CISR2ASC_H__", "", "#ifdef __cplusplus", 'extern "C"', "{",
          "#endif", ""]
    for row in ROWS:
        gt = t["glyph_tables"][row]
        pairs = gt["pairs"]
        if len(pairs) > gt["size"]:
            raise ValueError(f"glyph table {row}: {len(pairs)} initialisers for size {gt['size']}")
        L.append(f"  static int cisr_{row}[{gt['size']}][2] = {{")
        L += [f"    {{{int(a)}, {int(b)}}}" + ("," if i < len(pairs) - 1 else "") for i, (a, b) in enumerate(pairs)]
        L += ["  };", ""]
    L += ["#ifdef __cplusplus", "}", "#endif", "", "#endif", ""]
    return "\n".join(L)


def write_headers(t: dict, out_dir: Path) -> list[Path]:
    from repsynth.software import write_if_changed
    out_dir.mkdir(parents=True, exist_ok=True)
    a, c = out_dir / "apcisr.h", out_dir / "cisr2asc.h"
    write_if_changed(a, emit_apcisr_h(t))
    write_if_changed(c, emit_cisr2asc_h(t))
    return [a, c]


def dump_tables(header_dir: Path, work: Path, dumper_c: Path) -> str:
    """Compile conformance/runners/script/dump_tables.c against the headers in header_dir and run it."""
    work.mkdir(parents=True, exist_ok=True)
    exe = work / "dump_tables"
    r = subprocess.run(["gcc", "-std=gnu99", "-w", f"-I{header_dir}", "-o", str(exe), str(dumper_c)],
                       capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f"dumper did not compile against {header_dir}: {r.stderr[-1500:]}")
    return subprocess.run([str(exe)], capture_output=True, text=True, check=True).stdout


def table_model_from_dump(dump: str) -> dict:
    """Reads a dump back into the table model (used to read APCISR's own tables as the compiler sees them)."""
    entries, gt = [], {}
    for line in dump.splitlines():
        f = line.split()
        if f[0] == "entry":
            kv = dict(x.split("=", 1) for x in f[2:])
            entries.append({"rmn": bytes.fromhex(kv["rmn"]).decode("latin-1") if kv["rmn"] != "-" else "",
                            "acii_hex": "" if kv["acii"] == "-" else kv["acii"], "purna": int(kv["purna"]),
                            "grid": [int(x) for x in kv["grid"].split(",")]})
        elif f[0].startswith("cisr_") and f[1].startswith("size="):
            gt[f[0][5:]] = {"size": int(f[1][5:]), "pairs": []}
        elif f[0].startswith("cisr_"):
            gt[f[0][5:]]["pairs"].append([int(f[2]), int(f[3])])
    return {"entries": entries, "glyph_tables": gt}


def table_model(spec: dict, spec_sha: str) -> dict:
    """The table model of a script_structure specification, in either of the two forms the tree holds:
    the P1.6 extraction of APCISR's own Devanagari chart (encoding.grid_table, cells as 3 x 3, written by the
    intake lane) or a candidate made by gen/script/derive.py (structure.grid_table with glyph tables).
    The P1.6 extraction carries no glyph tables: its build keeps APCISR's own cisr2asc.h (glyph_tables None)."""
    ident = spec["identity"]
    if "grid_table" in spec.get("encoding", {}) and isinstance(spec["encoding"]["grid_table"], list):
        entries = []
        for row in spec["encoding"]["grid_table"]:
            g = row["grid"]
            flat = [int(x) for r in g for x in r] if isinstance(g[0], list) else [int(x) for x in g]
            entries.append({"rmn": row["romenagri"], "acii_hex": row["acii"], "purna": int(row["purna"]), "grid": flat})
        return {"id": ident["id"], "title": ident["title"], "spec_sha256": spec_sha, "candidate": False,
                "charset": "ACII (ISCII bytes, as Romenagri's uni2acii writes them)", "entries": entries, "glyph_tables": None}
    s = spec["structure"]
    return {"id": ident["id"], "title": ident["title"], "spec_sha256": spec_sha, "candidate": True,
            "charset": spec["encoding"]["input"], "entries": s["grid_table"], "glyph_tables": s["glyph_tables"]}
