"""Direct HDL generator (HDL-01, P5.1): SystemVerilog and VHDL-2008 units from a numeric specification.

Balanced ternary: every unit decodes its operands trit by trit through the code table of the
specification's active encoding (/encoding/active, /encoding/encodings), computes on an internal
(plus, minus) pair per trit with cells whose truth tables are derived here from integer arithmetic,
and encodes the result through the same table. Switching the encoding from pair to planes changes the
code table or the bit positions of every trit, so every unit regenerates (change D2(d)).

Binary integer: the baseline add and mul units of P5.11, as plain two's complement operators.

Declared reads (DEP-01) are given per unit by reads_for(); the lane reads only through the
recording accessor, so a read outside them fails with the path.
"""
from __future__ import annotations

GENERATOR = "repsynth.gen.hdl 0.3.0"
NOTICE = "© 1993–2026 Abhishek Choudhary. All rights reserved. AyeAI."
# Operations this generator can build. Which of them are built is the lane's promoted set.
BT_OPS = ("add", "sub", "neg", "mul", "cmp", "shl", "shr", "from_int", "to_int")
BIN_OPS = ("add", "mul")


# ---------------------------------------------------------------- tables derived from integer arithmetic

def _trit_bits(t: int) -> tuple[int, int]:
    """Internal form of a trit: (plus, minus); value = plus - minus."""
    return (1 if t == 1 else 0, 1 if t == -1 else 0)


def add_cell_table():
    """Full balanced-ternary adder: (a, b, cin) -> (sum, cout) with a + b + cin = sum + 3 cout.
    Rows: (input bits ap am bp bm cp cm, output bits sp sm op om)."""
    rows = []
    for a in (-1, 0, 1):
        for b in (-1, 0, 1):
            for c in (-1, 0, 1):
                s = a + b + c
                co = 1 if s > 1 else (-1 if s < -1 else 0)
                sm = s - 3 * co
                assert -1 <= sm <= 1 and a + b + c == sm + 3 * co
                ins = (*_trit_bits(a), *_trit_bits(b), *_trit_bits(c))
                outs = (*_trit_bits(sm), *_trit_bits(co))
                rows.append((ins, outs, (a, b, c, sm, co)))
    return rows


def cmp_cell_table():
    """Trit comparison: (a, b) -> (gt, lt)."""
    rows = []
    for a in (-1, 0, 1):
        for b in (-1, 0, 1):
            rows.append(((*_trit_bits(a), *_trit_bits(b)), (int(a > b), int(a < b)), (a, b)))
    return rows


def code_table(enc: dict, name: str):
    """From the encoding's codes: code (two-bit string 'hl') -> (plus, minus, invalid)."""
    codes = enc["codes"]
    if sorted(codes.keys()) != ["-1", "0", "1"]:
        raise ValueError(f"/encoding/encodings/{name}/codes must define -1, 0 and 1")
    table = {}
    for k, c in codes.items():
        if len(c) != 2 or set(c) - {"0", "1"}:
            raise ValueError(f"/encoding/encodings/{name}/codes/{k} must be two bits")
        p, m = _trit_bits(int(k))
        table[c] = (p, m, 0)
    for c in enc["invalid_codes"]:
        if c in table:
            raise ValueError(f"/encoding/encodings/{name}: code {c} is both valid and invalid")
        table[c] = (0, 0, 1)
    if sorted(table) != ["00", "01", "10", "11"]:
        raise ValueError(f"/encoding/encodings/{name}: codes and invalid codes must cover all four patterns")
    enc_of = {_trit_bits(int(k)): c for k, c in codes.items()}
    return table, enc_of


def layout_positions(enc: dict, name: str, n: int):
    """Bit positions (high, low) of trit i's code, as index expressions in i and n."""
    lay = enc["layout"]
    if lay == "interleaved":
        return ("2*i+1", "2*i"), lambda i: (2 * i + 1, 2 * i)
    if lay == "planes":
        return (f"{n}+i", "i"), lambda i: (n + i, i)
    raise ValueError(f"/encoding/encodings/{name}/layout: unknown layout {lay!r}")


# ---------------------------------------------------------------- SystemVerilog

def _sv_header(sid, ver, enc_name, digest, unit, what):
    return [
        f"// {NOTICE}",
        "// SPDX-License-Identifier: CERN-OHL-S-2.0",
        f"// Generated by {GENERATOR} from {sid} {ver}" + (f", encoding '{enc_name}'" if enc_name else "") + ". Do not edit.",
        f"// Specification slice sha256 (declared reads): {digest}",
        f"// Unit {unit}: {what}",
    ]


def _sv_bt_funcs(table, enc_of):
    L = ["  // Code table of the active encoding: code -> {invalid, minus, plus}.",
         "  function automatic logic [2:0] dec(input logic [1:0] c);",
         "    case (c)"]
    for c in ("00", "01", "10"):
        p, m, inv = table[c]
        L.append(f"      2'b{c}: dec = 3'b{inv}{m}{p};")
    p, m, inv = table["11"]
    L += [f"      default: dec = 3'b{inv}{m}{p};", "    endcase", "  endfunction",
          "  // Internal trit {minus, plus} -> code of the active encoding.",
          "  function automatic logic [1:0] enc(input logic [1:0] mp);",
          "    case (mp)"]
    L.append(f"      2'b01: enc = 2'b{enc_of[(1, 0)]};")
    L.append(f"      2'b10: enc = 2'b{enc_of[(0, 1)]};")
    L.append(f"      default: enc = 2'b{enc_of[(0, 0)]};")
    L += ["    endcase", "  endfunction"]
    return L


def _sv_add_cell():
    L = ["  // Balanced-ternary full adder; input {ap, am, bp, bm, cp, cm}, output {sp, sm, op, om}.",
         "  function automatic logic [3:0] tadd(input logic [5:0] x);",
         "    case (x)"]
    for ins, outs, (a, b, c, s, co) in add_cell_table():
        L.append(f"      6'b{''.join(map(str, ins))}: tadd = 4'b{''.join(map(str, outs))}; // {a:+d} {b:+d} {c:+d} = {s:+d} + 3*{co:+d}")
    L += ["      default: tadd = 4'b0000;", "    endcase", "  endfunction"]
    return L


def _sv_cmp_cell():
    L = ["  // Trit comparison; input {ap, am, bp, bm}, output {gt, lt}.",
         "  function automatic logic [1:0] tcmp(input logic [3:0] x);",
         "    case (x)"]
    for ins, outs, (a, b) in cmp_cell_table():
        L.append(f"      4'b{''.join(map(str, ins))}: tcmp = 2'b{''.join(map(str, outs))}; // {a:+d} vs {b:+d}")
    L += ["      default: tcmp = 2'b00;", "    endcase", "  endfunction"]
    return L


UNARY = ("neg", "from_int", "to_int")
BINARY_B = ("shl", "shr")          # b is a two's complement shift count, not a trit word


def _log2(w: int) -> int:
    k = w.bit_length() - 1
    if 1 << k != w:
        raise ValueError(f"register width {w} is not a power of two")
    return k


def sv_bt_unit(op, n, table, enc_of, pos_expr, hdr):
    W = 2 * n
    hi, lo = pos_expr
    unary = op in UNARY
    ports = [f"  input  logic [{W-1}:0] a,"]
    if not unary:
        ports.append(f"  input  logic [{W-1}:0] b,")
    ports.append(f"  output logic [{W-1}:0] r")
    name = f"bt_{op}{n}"
    L = hdr + [f"module {name} (", *ports, ");", f"  localparam int N = {n};"]
    L += _sv_bt_funcs(table, enc_of)
    if op in ("add", "sub", "mul", "from_int"):
        L += _sv_add_cell()
    if op == "cmp":
        L += _sv_cmp_cell()
    if op == "from_int":
        return name, "\n".join(L + _sv_from_int(n, W, hi, lo))
    names = ["a"] if (unary or op in BINARY_B) else ["a", "b"]
    for x in names:
        L += [f"  logic [N-1:0] {x}p, {x}m, {x}i;",
              "  always_comb begin",
              "    for (int i = 0; i < N; i++) begin",
              f"      {{{x}i[i], {x}m[i], {x}p[i]}} = dec({{{x}[{hi}], {x}[{lo}]}});",
              "    end",
              "  end"]
    inv = " || ".join(f"(|{x}i)" for x in names)
    L.append(f"  logic invalid;\n  assign invalid = {inv};")
    if op == "cmp":
        L += ["  logic gt, lt;",
              "  always_comb begin",
              "    logic [1:0] c;",
              "    gt = 1'b0; lt = 1'b0;",
              "    for (int i = 0; i < N; i++) begin  // the most significant differing trit decides",
              "      c = tcmp({ap[i], am[i], bp[i], bm[i]});",
              "      if (c != 2'b00) begin gt = c[1]; lt = c[0]; end",
              "    end",
              "  end",
              "  always_comb begin",
              f"    if (invalid) r = {W}'d2;",
              f"    else if (lt) r = {{{W}{{1'b1}}}};",
              f"    else if (gt) r = {W}'d1;",
              f"    else r = {W}'d0;",
              "  end",
              "endmodule", ""]
        return name, "\n".join(L)
    if op == "to_int":
        L += ["  always_comb begin  // value = sum of trit i times 3^i, as a two's complement word",
              "    logic [W-1:0] acc;",
              "    acc = '0;",
              "    for (int i = N-1; i >= 0; i--) begin",
              "      acc = (acc << 1) + acc + {{(W-1){am[i]}}, ap[i] | am[i]};  // acc * 3 + trit",
              "    end",
              "    r = invalid ? {1'b1, {(W-1){1'b0}}} : acc;  // invalid: the most negative integer",
              "  end",
              "endmodule", ""]
        L.insert(L.index(f"  localparam int N = {n};") + 1, f"  localparam int W = {W};")
        return name, "\n".join(L)
    L.append("  logic [N-1:0] rp, rm;")
    if op == "neg":
        L += ["  assign rp = am;", "  assign rm = ap;"]
    elif op in BINARY_B:
        K = _log2(W)
        d = "<<" if op == "shl" else ">>"
        L += [f"  // k = b modulo the register width; trits shifted past either end are lost, so k >= N gives 0.",
              f"  logic [{K-1}:0] k;",
              f"  assign k = b[{K-1}:0];",
              f"  logic unused_b;",
              f"  assign unused_b = ^b[{W-1}:{K}];",
              f"  assign rp = ap {d} k;",
              f"  assign rm = am {d} k;"]
    elif op in ("add", "sub"):
        yp, ym = ("bp", "bm") if op == "add" else ("bm", "bp")  # sub: a + (-b), -b swaps plus and minus
        L += ["  always_comb begin",
              "    logic cp, cm;",
              "    logic [3:0] o;",
              "    cp = 1'b0; cm = 1'b0;",
              "    for (int i = 0; i < N; i++) begin  // the carry out of trit N-1 is dropped: wrap modulo 3^N",
              f"      o = tadd({{ap[i], am[i], {yp}[i], {ym}[i], cp, cm}});",
              "      rp[i] = o[3]; rm[i] = o[2]; cp = o[1]; cm = o[0];",
              "    end",
              "  end"]
    elif op == "mul":
        L += ["  always_comb begin  // low N trits: accumulate b[j] * a * 3^j, each sum wrapping modulo 3^N",
              "    logic [N-1:0] sp, sm;",
              "    logic pp, pm, cp, cm;",
              "    logic [3:0] o;",
              "    sp = '0; sm = '0;",
              "    for (int j = 0; j < N; j++) begin",
              "      cp = 1'b0; cm = 1'b0;",
              "      for (int i = j; i < N; i++) begin",
              "        pp = (ap[i-j] & bp[j]) | (am[i-j] & bm[j]);",
              "        pm = (ap[i-j] & bm[j]) | (am[i-j] & bp[j]);",
              "        o = tadd({sp[i], sm[i], pp, pm, cp, cm});",
              "        sp[i] = o[3]; sm[i] = o[2]; cp = o[1]; cm = o[0];",
              "      end",
              "    end",
              "    rp = sp; rm = sm;",
              "  end"]
    else:
        raise ValueError(f"no direct unit for balanced ternary operation {op!r}")
    L += ["  always_comb begin",
          f"    r = '0;",
          "    for (int i = 0; i < N; i++) begin",
          f"      {{r[{hi}], r[{lo}]}} = enc({{rm[i], rp[i]}});",
          "    end",
          f"    if (invalid) r = {{{W}{{1'b1}}}};  // the invalid word: every bit set",
          "  end",
          "endmodule", ""]
    return name, "\n".join(L)


def _sv_from_int(n, W, hi, lo):
    """from_int: a two's complement word read most significant bit first, acc = 2 acc + bit, with the
    sign bit weighing -1; every step is one ternary ripple addition acc + acc + bit whose carry out is
    dropped, so the result wraps modulo 3^N."""
    return ["  logic [N-1:0] rp, rm;",
            "  always_comb begin",
            "    logic [N-1:0] sp, sm;",
            "    logic cp, cm;",
            "    logic [3:0] o;",
            "    sp = '0; sm = '0;",
            f"    for (int j = {W-1}; j >= 0; j--) begin",
            f"      cp = (j != {W-1}) && a[j];  // a bit of weight +2^j",
            f"      cm = (j == {W-1}) && a[j];  // the sign bit, weight -2^{W-1}",
            "      for (int i = 0; i < N; i++) begin",
            "        o = tadd({sp[i], sm[i], sp[i], sm[i], cp, cm});",
            "        sp[i] = o[3]; sm[i] = o[2]; cp = o[1]; cm = o[0];",
            "      end",
            "    end",
            "    rp = sp; rm = sm;",
            "  end",
            "  always_comb begin",
            "    r = '0;",
            "    for (int i = 0; i < N; i++) begin",
            f"      {{r[{hi}], r[{lo}]}} = enc({{rm[i], rp[i]}});",
            "    end",
            "  end",
            "endmodule", ""]


def sv_bin_unit(op, w, hdr):
    name = f"bin_{op}{w}"
    expr = {"add": "a + b", "mul": "a * b"}[op]
    L = hdr + [f"module {name} (",
               f"  input  logic [{w-1}:0] a,",
               f"  input  logic [{w-1}:0] b,",
               f"  output logic [{w-1}:0] r",
               ");",
               f"  assign r = {expr};  // modulo 2^{w}: the low {w} bits",
               "endmodule", ""]
    return name, "\n".join(L)


# ---------------------------------------------------------------- VHDL-2008

def _vh_header(sid, ver, enc_name, digest, unit, what):
    return [
        f"-- {NOTICE}",
        "-- SPDX-License-Identifier: CERN-OHL-S-2.0",
        f"-- Generated by {GENERATOR} from {sid} {ver}" + (f", encoding '{enc_name}'" if enc_name else "") + ". Do not edit.",
        f"-- Specification slice sha256 (declared reads): {digest}",
        f"-- Unit {unit}: {what}",
        "library ieee;",
        "use ieee.std_logic_1164.all;",
        "use ieee.numeric_std.all;",
    ]


def _vh_bt_funcs(table, enc_of):
    L = ["  -- Code table of the active encoding: code -> (invalid, minus, plus).",
         "  function dec(c : std_logic_vector(1 downto 0)) return std_logic_vector is",
         "  begin",
         "    case c is"]
    for c in ("00", "01", "10"):
        p, m, inv = table[c]
        L.append(f'      when "{c}" => return "{inv}{m}{p}";')
    p, m, inv = table["11"]
    L += [f'      when others => return "{inv}{m}{p}";', "    end case;", "  end function;",
          "  -- Internal trit (minus, plus) -> code of the active encoding.",
          "  function enc(mp : std_logic_vector(1 downto 0)) return std_logic_vector is",
          "  begin",
          "    case mp is",
          f'      when "01" => return "{enc_of[(1, 0)]}";',
          f'      when "10" => return "{enc_of[(0, 1)]}";',
          f'      when others => return "{enc_of[(0, 0)]}";',
          "    end case;", "  end function;"]
    return L


def _vh_add_cell():
    L = ["  -- Balanced-ternary full adder; input (ap, am, bp, bm, cp, cm), output (sp, sm, op, om).",
         "  function tadd(x : std_logic_vector(5 downto 0)) return std_logic_vector is",
         "  begin",
         "    case x is"]
    for ins, outs, (a, b, c, s, co) in add_cell_table():
        L.append(f'      when "{"".join(map(str, ins))}" => return "{"".join(map(str, outs))}"; -- {a:+d} {b:+d} {c:+d} = {s:+d} + 3*{co:+d}')
    L += ['      when others => return "0000";', "    end case;", "  end function;"]
    return L


def _vh_cmp_cell():
    L = ["  -- Trit comparison; input (ap, am, bp, bm), output (gt, lt).",
         "  function tcmp(x : std_logic_vector(3 downto 0)) return std_logic_vector is",
         "  begin",
         "    case x is"]
    for ins, outs, (a, b) in cmp_cell_table():
        L.append(f'      when "{"".join(map(str, ins))}" => return "{"".join(map(str, outs))}"; -- {a:+d} vs {b:+d}')
    L += ['      when others => return "00";', "    end case;", "  end function;"]
    return L


def vh_bt_unit(op, n, table, enc_of, pos_fn, hdr):
    W = 2 * n
    unary = op in UNARY
    name = f"bt_{op}{n}"
    hi_e, lo_e = pos_fn
    ports = [f"    a : in  std_logic_vector({W-1} downto 0);"]
    if not unary:
        ports.append(f"    b : in  std_logic_vector({W-1} downto 0);")
    ports.append(f"    r : out std_logic_vector({W-1} downto 0)")
    L = hdr + [f"entity {name} is", "  port (", *ports, "  );", f"end entity {name};", "",
               f"architecture direct of {name} is", f"  constant N : natural := {n};",
               "  subtype tv is std_logic_vector(N-1 downto 0);"]
    L += _vh_bt_funcs(table, enc_of)
    if op in ("add", "sub", "mul", "from_int"):
        L += _vh_add_cell()
    if op == "cmp":
        L += _vh_cmp_cell()
    if op == "from_int":
        return name, "\n".join(L + _vh_from_int(n, W, hi_e, lo_e))
    names = ["a"] if (unary or op in BINARY_B) else ["a", "b"]
    for x in names:
        L.append(f"  signal {x}p, {x}m, {x}i : tv;")
    L += ["  signal invalid : std_logic;", "  signal rp, rm : tv;", "begin"]
    for x in names:
        L += [f"  decode_{x} : process (all)",
              "    variable d : std_logic_vector(2 downto 0);",
              "  begin",
              "    for i in 0 to N-1 loop",
              f"      d := dec({x}({hi_e}) & {x}({lo_e}));",
              f"      {x}i(i) <= d(2); {x}m(i) <= d(1); {x}p(i) <= d(0);",
              "    end loop;",
              "  end process;"]
    inv = " or ".join(f"or {x}i" for x in names)
    L.append(f"  invalid <= {inv};")
    if op == "cmp":
        L += ["  compare : process (all)",
              "    variable c : std_logic_vector(1 downto 0);",
              "    variable gt, lt : std_logic;",
              "  begin",
              "    gt := '0'; lt := '0';",
              "    for i in 0 to N-1 loop  -- the most significant differing trit decides",
              "      c := tcmp(ap(i) & am(i) & bp(i) & bm(i));",
              "      if c /= \"00\" then gt := c(1); lt := c(0); end if;",
              "    end loop;",
              "    if invalid = '1' then r <= std_logic_vector(to_unsigned(2, r'length));",
              "    elsif lt = '1' then r <= (others => '1');",
              "    elsif gt = '1' then r <= std_logic_vector(to_unsigned(1, r'length));",
              "    else r <= (others => '0');",
              "    end if;",
              "  end process;",
              "  rp <= (others => '0');",
              "  rm <= (others => '0');",
              f"end architecture direct;", ""]
        return name, "\n".join(L)
    if op == "to_int":
        L += ["  to_twos : process (all)  -- value = sum of trit i times 3^i, as a two's complement word",
              f"    variable acc : unsigned({W-1} downto 0);",
              f"    variable t : unsigned({W-1} downto 0);",
              "  begin",
              "    acc := (others => '0');",
              "    for i in N-1 downto 0 loop",
              "      if am(i) = '1' then t := (others => '1');",
              "      elsif ap(i) = '1' then t := to_unsigned(1, t'length);",
              "      else t := (others => '0');",
              "      end if;",
              "      acc := shift_left(acc, 1) + acc + t;  -- acc * 3 + trit",
              "    end loop;",
              "    if invalid = '1' then  -- invalid: the most negative integer",
              "      acc := (others => '0'); acc(acc'high) := '1';",
              "    end if;",
              "    r <= std_logic_vector(acc);",
              "  end process;",
              "  rp <= (others => '0');",
              "  rm <= (others => '0');",
              "end architecture direct;", ""]
        return name, "\n".join(L)
    if op == "neg":
        L += ["  rp <= am;", "  rm <= ap;"]
    elif op in BINARY_B:
        K = _log2(W)
        fn = "shift_left" if op == "shl" else "shift_right"
        L += ["  -- k = b modulo the register width; trits shifted past either end are lost, so k >= N gives 0.",
              "  shifter : process (all)",
              "    variable k : natural;",
              "  begin",
              f"    k := to_integer(unsigned(b({K-1} downto 0)));",
              f"    rp <= std_logic_vector({fn}(unsigned(ap), k));",
              f"    rm <= std_logic_vector({fn}(unsigned(am), k));",
              "  end process;"]
    elif op in ("add", "sub"):
        yp, ym = ("bp", "bm") if op == "add" else ("bm", "bp")
        L += ["  adder : process (all)",
              "    variable cp, cm : std_logic;",
              "    variable o : std_logic_vector(3 downto 0);",
              "  begin",
              "    cp := '0'; cm := '0';",
              "    for i in 0 to N-1 loop  -- the carry out of trit N-1 is dropped: wrap modulo 3^N",
              f"      o := tadd(ap(i) & am(i) & {yp}(i) & {ym}(i) & cp & cm);",
              "      rp(i) <= o(3); rm(i) <= o(2); cp := o(1); cm := o(0);",
              "    end loop;",
              "  end process;"]
    elif op == "mul":
        L += ["  multiplier : process (all)  -- low N trits: accumulate b(j) * a * 3^j, each sum wrapping",
              "    variable sp, sm : tv;",
              "    variable pp, pm, cp, cm : std_logic;",
              "    variable o : std_logic_vector(3 downto 0);",
              "  begin",
              "    sp := (others => '0'); sm := (others => '0');",
              "    for j in 0 to N-1 loop",
              "      cp := '0'; cm := '0';",
              "      for i in j to N-1 loop",
              "        pp := (ap(i-j) and bp(j)) or (am(i-j) and bm(j));",
              "        pm := (ap(i-j) and bm(j)) or (am(i-j) and bp(j));",
              "        o := tadd(sp(i) & sm(i) & pp & pm & cp & cm);",
              "        sp(i) := o(3); sm(i) := o(2); cp := o(1); cm := o(0);",
              "      end loop;",
              "    end loop;",
              "    rp <= sp; rm <= sm;",
              "  end process;"]
    else:
        raise ValueError(f"no direct unit for balanced ternary operation {op!r}")
    L += ["  encode : process (all)",
          f"    variable w : std_logic_vector({W-1} downto 0);",
          "    variable c : std_logic_vector(1 downto 0);",
          "  begin",
          "    w := (others => '0');",
          "    for i in 0 to N-1 loop",
          "      c := enc(rm(i) & rp(i));",
          f"      w({hi_e}) := c(1); w({lo_e}) := c(0);",
          "    end loop;",
          "    if invalid = '1' then w := (others => '1'); end if;  -- the invalid word: every bit set",
          "    r <= w;",
          "  end process;",
          "end architecture direct;", ""]
    return name, "\n".join(L)


def _vh_from_int(n, W, hi_e, lo_e):
    return ["  signal rp, rm : tv;",
            "begin",
            "  convert : process (all)  -- acc = 2 acc + bit, the sign bit weighing -1; carries out dropped",
            "    variable sp, sm : tv;",
            "    variable cp, cm : std_logic;",
            "    variable o : std_logic_vector(3 downto 0);",
            "  begin",
            "    sp := (others => '0'); sm := (others => '0');",
            f"    for j in {W-1} downto 0 loop",
            f"      if j = {W-1} then cp := '0'; cm := a(j); else cp := a(j); cm := '0'; end if;",
            "      for i in 0 to N-1 loop",
            "        o := tadd(sp(i) & sm(i) & sp(i) & sm(i) & cp & cm);",
            "        sp(i) := o(3); sm(i) := o(2); cp := o(1); cm := o(0);",
            "      end loop;",
            "    end loop;",
            "    rp <= sp; rm <= sm;",
            "  end process;",
            "  encode : process (all)",
            f"    variable w : std_logic_vector({W-1} downto 0);",
            "    variable c : std_logic_vector(1 downto 0);",
            "  begin",
            "    w := (others => '0');",
            "    for i in 0 to N-1 loop",
            "      c := enc(rm(i) & rp(i));",
            f"      w({hi_e}) := c(1); w({lo_e}) := c(0);",
            "    end loop;",
            "    r <= w;",
            "  end process;",
            "end architecture direct;", ""]


def vh_bin_unit(op, w, hdr):
    name = f"bin_{op}{w}"
    if op == "add":
        body = ["  r <= std_logic_vector(unsigned(a) + unsigned(b));"]
    else:
        body = ["  r <= std_logic_vector(resize(unsigned(a) * unsigned(b), r'length));"]
    L = hdr + [f"entity {name} is", "  port (",
               f"    a : in  std_logic_vector({w-1} downto 0);",
               f"    b : in  std_logic_vector({w-1} downto 0);",
               f"    r : out std_logic_vector({w-1} downto 0)",
               "  );", f"end entity {name};", "",
               f"architecture direct of {name} is", "begin",
               f"  -- modulo 2^{w}: the low {w} bits", *body,
               "end architecture direct;", ""]
    return name, "\n".join(L)


