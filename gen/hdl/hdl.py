def reads_for(sid: str, op_index: int) -> list[str]:
    """Exact declared reads of the unit of one operation (DEP-01): never the whole operation list, so
    appending an operation (change D2(c)) leaves every existing unit unchanged."""
    base = ["/identity/id", "/identity/version", f"/operations/{op_index}", "/domain/widths"]
    if sid == "balanced_ternary":
        base += ["/encoding/active", "/encoding/encodings"]
    elif sid != "binary_integer":
        raise ValueError(f"no HDL generator for specification {sid!r}")
    return base


def generate(read, digest: str, op_index: int, lang: str) -> dict:
    """read(pointer) reads through the recording accessor; digest is the sha256 over the declared
    slices; op_index selects /operations/<i>; lang is 'sv' or 'vhdl'.
    Returns {"files": {relative path: text}, "units": [metadata]}."""
    if lang not in ("sv", "vhdl"):
        raise ValueError(f"unknown language {lang!r}")
    sid = read("/identity/id")
    ver = read("/identity/version")
    opd = read(f"/operations/{op_index}")
    op = opd["name"]
    widths = [w["digits"] for w in read("/domain/widths")]
    files, units = {}, []
    if sid == "balanced_ternary":
        if op not in BT_OPS:
            raise ValueError(f"balanced_ternary operation {op!r} has no direct unit")
        active = read("/encoding/active")
        encs = read("/encoding/encodings")
        if active not in encs:
            raise ValueError(f"/encoding/active names {active!r}, which /encoding/encodings does not define")
        enc = encs[active]
        table, enc_of = code_table(enc, active)
        for n in widths:
            pos_expr, _ = layout_positions(enc, active, n)
            nm = f"bt_{op}{n}"
            what = f"{opd['meaning']}; {n} trits in {2*n} bits"
            if lang == "sv":
                _, text = sv_bt_unit(op, n, table, enc_of, pos_expr, _sv_header(sid, ver, active, digest, nm, what))
                files[f"sv/{nm}.sv"] = text
            else:
                _, text = vh_bt_unit(op, n, table, enc_of, pos_expr, _vh_header(sid, ver, active, digest, nm, what))
                files[f"vhdl/{nm}.vhd"] = text
            units.append({"unit": nm, "spec": sid, "op": op, "digits": n, "register_bits": 2 * n,
                          "arity": opd["arity"], "encoding": active, "route": "direct"})
    elif sid == "binary_integer":
        if op not in BIN_OPS:
            raise ValueError(f"binary_integer operation {op!r} has no direct unit")
        for w in widths:
            nm = f"bin_{op}{w}"
            what = f"{opd['meaning']}; {w} bits"
            if lang == "sv":
                files[f"sv/{nm}.sv"] = sv_bin_unit(op, w, _sv_header(sid, ver, None, digest, nm, what))[1]
            else:
                files[f"vhdl/{nm}.vhd"] = vh_bin_unit(op, w, _vh_header(sid, ver, None, digest, nm, what))[1]
            units.append({"unit": nm, "spec": sid, "op": op, "digits": w, "register_bits": w,
                          "arity": opd["arity"], "encoding": "twos_complement", "route": "direct"})
    else:
        raise ValueError(f"no HDL generator for specification {sid!r}")
    return {"files": files, "units": units}
