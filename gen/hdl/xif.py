"""CV-X-IF coprocessor generator (HDL-05, P5.5).

Writes one SystemVerilog coprocessor that attaches the generated 16-trit balanced ternary units to a
32-bit core through the OpenHW eXtension interface (cv32e40x_if_xif). The instruction decoder is built
from the allocation ledger entries (ledger/allocations/<spec>/<op>.yaml, match and mask), so the
coprocessor accepts exactly the encodings the toolchain and QEMU use. It never invents an encoding: an
operation without a ledger entry is refused.

Protocol (CV-X-IF as cv32e40x implements it): an accepted instruction is held until the core commits
it; a killed instruction is dropped; a committed one returns its result on the result interface, with
one instruction in flight at a time (issue_ready is low while one is held)."""
from __future__ import annotations

GENERATOR = "repsynth.gen.hdl.xif 0.3.0"
NOTICE = "© 1993–2026 Abhishek Choudhary. All rights reserved. AyeAI."


def generate(entries: list[dict], unit_digits: int, ledger_hashes: dict) -> str:
    """entries: ledger entries (spec, op, mnemonic, match, mask, rs2). Returns the SystemVerilog text."""
    if not entries:
        raise ValueError("no ledger entries: nothing to decode")
    if len(entries) > 16:
        raise ValueError("more than sixteen operations: widen the selector")
    L = [f"// {NOTICE}",
         "// SPDX-License-Identifier: CERN-OHL-S-2.0",
         f"// Generated by {GENERATOR} from the allocation ledger. Do not edit.",
         "// Ledger entries (path: sha256):"]
    L += [f"//   {p}: {h}" for p, h in sorted(ledger_hashes.items())]
    L += ["// CV-X-IF coprocessor for the balanced ternary units on a 32-bit core.",
          "module rs_xif_xayebt #(",
          "  parameter int unsigned X_ID_WIDTH = 4",
          ") (",
          "  input  logic clk_i,",
          "  input  logic rst_ni,",
          "  cv32e40x_if_xif.coproc_compressed xif_compressed_if,",
          "  cv32e40x_if_xif.coproc_issue      xif_issue_if,",
          "  cv32e40x_if_xif.coproc_commit     xif_commit_if,",
          "  cv32e40x_if_xif.coproc_mem        xif_mem_if,",
          "  cv32e40x_if_xif.coproc_mem_result xif_mem_result_if,",
          "  cv32e40x_if_xif.coproc_result     xif_result_if",
          ");",
          "  // No compressed instructions and no memory accesses are offered.",
          "  assign xif_compressed_if.compressed_ready = 1'b1;",
          "  assign xif_compressed_if.compressed_resp  = '0;",
          "  assign xif_mem_if.mem_valid = 1'b0;",
          "  assign xif_mem_if.mem_req   = '0;",
          "",
          "  logic [31:0] instr, rs1, rs2;",
          "  assign instr = xif_issue_if.issue_req.instr;",
          "  assign rs1   = xif_issue_if.issue_req.rs[0];",
          "  assign rs2   = xif_issue_if.issue_req.rs[1];",
          "",
          "  // Decoder from the ledger: (instr & mask) == match.",
          "  logic       hit, need_rs2;",
          "  logic [3:0] sel;",
          "  always_comb begin",
          "    hit = 1'b0; need_rs2 = 1'b0; sel = 4'd0;"]
    for i, e in enumerate(entries):
        m, k = int(str(e["match"]), 16), int(str(e["mask"]), 16)
        rs2 = "1'b1" if e["rs2"] == "register" else "1'b0"
        L.append(f"    if ((instr & 32'h{k:08x}) == 32'h{m:08x}) begin hit = 1'b1; sel = 4'd{i}; need_rs2 = {rs2}; end  // {e['mnemonic']}")
    L += ["  end", ""]
    for i, e in enumerate(entries):
        ports = ".a(rs1), .b(rs2)" if e["rs2"] == "register" else ".a(rs1)"
        L.append(f"  logic [31:0] r{i};")
        L.append(f"  bt_{e['op']}{unit_digits} u{i} ({ports}, .r(r{i}));")
    L += ["  logic [31:0] res;", "  always_comb begin", "    case (sel)"]
    for i, e in enumerate(entries):
        L.append(f"      4'd{i}: res = r{i};")
    L += ["      default: res = '0;", "    endcase", "  end", "",
          "  typedef enum logic [1:0] {IDLE, WAIT_COMMIT, RESULT} state_e;",
          "  state_e                st;",
          "  logic [X_ID_WIDTH-1:0] id_q;",
          "  logic [4:0]            rd_q;",
          "  logic [31:0]           data_q;",
          "  logic                  rs_ok, fire, commit_now, kill_now;",
          "  assign rs_ok = xif_issue_if.issue_req.rs_valid[0] && (!need_rs2 || xif_issue_if.issue_req.rs_valid[1]);",
          "  // Not ready while an instruction is held; an instruction that is not ours is answered at once.",
          "  assign xif_issue_if.issue_ready = (st == IDLE) && (!hit || rs_ok);",
          "  always_comb begin",
          "    xif_issue_if.issue_resp           = '0;",
          "    xif_issue_if.issue_resp.accept    = hit;",
          "    xif_issue_if.issue_resp.writeback = hit;",
          "  end",
          "  assign fire = xif_issue_if.issue_valid && xif_issue_if.issue_ready && hit;",
          "  assign commit_now = xif_commit_if.commit_valid &&",
          "                      xif_commit_if.commit.id == (st == IDLE ? xif_issue_if.issue_req.id : id_q);",
          "  assign kill_now = xif_commit_if.commit.commit_kill;",
          "",
          "  always_ff @(posedge clk_i or negedge rst_ni) begin",
          "    if (!rst_ni) begin",
          "      st <= IDLE; id_q <= '0; rd_q <= '0; data_q <= '0;",
          "    end else begin",
          "      case (st)",
          "        IDLE: if (fire) begin",
          "          id_q <= xif_issue_if.issue_req.id; rd_q <= instr[11:7]; data_q <= res;",
          "          if (commit_now) st <= kill_now ? IDLE : RESULT;",
          "          else st <= WAIT_COMMIT;",
          "        end",
          "        WAIT_COMMIT: if (commit_now) st <= kill_now ? IDLE : RESULT;",
          "        RESULT: if (xif_result_if.result_ready) st <= IDLE;",
          "        default: st <= IDLE;",
          "      endcase",
          "    end",
          "  end",
          "",
          "  assign xif_result_if.result_valid = (st == RESULT);",
          "  always_comb begin",
          "    xif_result_if.result      = '0;",
          "    xif_result_if.result.id   = id_q;",
          "    xif_result_if.result.data = data_q;",
          "    xif_result_if.result.rd   = rd_q;",
          "    xif_result_if.result.we   = 1'b1;",
          "  end",
          "endmodule", ""]
    return "\n".join(L)
