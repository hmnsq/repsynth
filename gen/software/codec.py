"""Generate the trit codec header from the balanced ternary specification's active encoding.

Declared reads (DEP-01): /identity/id, /identity/version, /encoding/active, /encoding/encodings.
This is the artefact that change D2(d) (pair to planes) regenerates.
"""
from __future__ import annotations

GENERATOR = "repsynth.gen.software.codec 0.3.0"
READS = ["/identity/id", "/identity/version", "/encoding/active", "/encoding/encodings"]


def generate(read) -> str:
    """read(pointer) returns the value at pointer through the recording accessor."""
    sid = read("/identity/id")
    ver = read("/identity/version")
    active = read("/encoding/active")
    encs = read("/encoding/encodings")
    if active not in encs:
        raise ValueError(f"/encoding/active names {active!r}, which /encoding/encodings does not define")
    enc = encs[active]
    codes = enc["codes"]
    if sorted(codes.keys()) != ["-1", "0", "1"]:
        raise ValueError("/encoding/encodings/%s/codes must define -1, 0 and 1" % active)
    for k, c in codes.items():
        if len(c) != 2 or set(c) - {"0", "1"}:
            raise ValueError(f"code for {k} must be two bits")
    inv = enc["invalid_codes"]
    # code bit string "hl": h is the high bit (bit 2i+1 or minus-plane bit), l the low bit.
    def val(code):
        return int(code, 2)
    lut = {val(c): int(k) for k, c in codes.items()}
    for c in inv:
        lut[val(c)] = 2
    if sorted(lut) != [0, 1, 2, 3]:
        raise ValueError("codes and invalid codes must cover all four two-bit patterns exactly once")
    enc_of = {int(k): val(c) for k, c in codes.items()}
    layout = enc["layout"]
    lines = [
        "/* © 1993–2026 Abhishek Choudhary. All rights reserved. AyeAI.",
        " * SPDX-License-Identifier: GPL-3.0-or-later",
        f" * Generated by {GENERATOR} from {sid} {ver}, encoding '{active}'. Do not edit. */",
        "#ifndef BT_CODEC_H",
        "#define BT_CODEC_H",
        "#include <stdint.h>",
        f'#define BT_ENCODING_NAME "{active}"',
        "/* Two-bit code of trit i of an n-trit word: high bit and low bit. */",
    ]
    if layout == "interleaved":
        lines += [
            "static inline unsigned bt_code_get(uint64_t w, unsigned i, unsigned n)",
            "{ (void)n; return (unsigned)((w >> (2u * i)) & 3u); }",
            "static inline uint64_t bt_code_put(uint64_t w, unsigned i, unsigned n, unsigned code)",
            "{ (void)n; return (w & ~((uint64_t)3u << (2u * i))) | ((uint64_t)(code & 3u) << (2u * i)); }",
        ]
    elif layout == "planes":
        lines += [
            "static inline unsigned bt_code_get(uint64_t w, unsigned i, unsigned n)",
            "{ return (unsigned)((((w >> (n + i)) & 1u) << 1) | ((w >> i) & 1u)); }",
            "static inline uint64_t bt_code_put(uint64_t w, unsigned i, unsigned n, unsigned code)",
            "{ w &= ~(((uint64_t)1u << i) | ((uint64_t)1u << (n + i)));",
            "  return w | ((uint64_t)(code & 1u) << i) | ((uint64_t)((code >> 1) & 1u) << (n + i)); }",
        ]
    else:
        raise ValueError(f"unknown layout {layout!r}")
    lines += [
        "/* Trit value of a code: -1, 0, +1, or 2 for an invalid code. */",
        "static inline int bt_code_value(unsigned code) {",
        f"  static const int lut[4] = {{{lut[0]}, {lut[1]}, {lut[2]}, {lut[3]}}};",
        "  return lut[code & 3u];",
        "}",
        "/* Code of a trit value -1, 0 or +1. */",
        "static inline unsigned bt_value_code(int t) {",
        f"  return t < 0 ? {enc_of[-1]}u : (t > 0 ? {enc_of[1]}u : {enc_of[0]}u);",
        "}",
        "#endif",
        "",
    ]
    return "\n".join(lines)
