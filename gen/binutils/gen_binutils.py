"""binutils patch path generator (ISA-08, P4.5): opcode entries, MATCH/MASK definitions, extension
registration and gas tests, as exact-anchor patches for the pinned binutils (applied by
gen/qemu/patch_qemu.py, which is tool-neutral).

Called through repsynth.lanes.graph_tiera (nodes gas:<sid>:<op> and gas:<sid>).
Generated files are compiled into binutils and so carry GPL-3.0-or-later."""
from __future__ import annotations

import json

GENERATOR = "repsynth.gen.binutils 0.3.0"
REGS = [("a0", 10), ("a1", 11), ("a2", 12), ("t0", 5), ("s1", 9), ("t6", 31)]


def _head(ctx, what: str, comment: str = "c") -> str:
    lines = ["© 1993–2026 Abhishek Choudhary. All rights reserved. AyeAI.",
             "SPDX-License-Identifier: GPL-3.0-or-later", what,
             f"Generated by {GENERATOR} from {ctx['sid']} {ctx['version']} (active encoding: {ctx['encoding']}).",
             f"slice_sha256: {ctx['slice_sha256']}", "Do not edit."]
    if comment == "#":
        return "".join(f"# {l}\n" for l in lines)
    return "/* " + "\n * ".join(lines) + " */\n"


def cname(mnemonic: str) -> str:
    return mnemonic.replace(".", "_").upper()


def _defines(e) -> str:
    c = cname(e["mnemonic"])
    return f"#define MATCH_{c} {e['match']}\n#define MASK_{c} {e['mask']}\n"


def _declare(e) -> str:
    c = cname(e["mnemonic"])
    return f"DECLARE_INSN({c.lower()}, MATCH_{c}, MASK_{c})\n"


def _entry(e, ext) -> str:
    c = cname(e["mnemonic"])
    args = "d,s" if e["rs2"] == "zero" else "d,s,t"
    return (f"{{\"{e['mnemonic']}\", 0, INSN_CLASS_{ext.upper()}, \"{args}\", MATCH_{c}, MASK_{c}, "
            f"match_opcode, 0 }},\n")


def _cases(e):
    """(source line, expected word, disassembly regex) for a few register choices."""
    out = []
    for i in range(3):
        rd, rs1, rs2 = REGS[i], REGS[i + 1], REGS[i + 2]
        word = int(e["match"], 16) | (rd[1] << 7) | (rs1[1] << 15)
        if e["rs2"] == "zero":
            src = f"\t{e['mnemonic']}\t{rd[0]}, {rs1[0]}"
            dis = f"{e['mnemonic']}[ \t]+{rd[0]},{rs1[0]}"
        else:
            word |= rs2[1] << 20
            src = f"\t{e['mnemonic']}\t{rd[0]}, {rs1[0]}, {rs2[0]}"
            dis = f"{e['mnemonic']}[ \t]+{rd[0]},{rs1[0]},{rs2[0]}"
        out.append((src, word, dis.replace(".", "\\.")))
    return out


def render_op(ctx: dict, root=None) -> dict:
    e, ext, sid = ctx["entry"], ctx["ext"]["extension"], ctx["sid"]
    b = f"gen/binutils/out/{sid}/ops/{ctx['op']['name']}"
    h = _head(ctx, f"{e['mnemonic']}: MATCH/MASK and DECLARE_INSN.") + _defines(e) + "/* DECLARE */\n" + _declare(e)
    c = _head(ctx, f"{e['mnemonic']}: riscv_opcodes entry.") + _entry(e, ext)
    s = _head(ctx, f"{e['mnemonic']}: gas test source lines.", "#") + "".join(x[0] + "\n" for x in _cases(e))
    return {f"{b}.opc.h": h, f"{b}.opc.c": c, f"{b}.s": s}


def render_spec(ctx: dict, root=None) -> dict:
    sid, ext = ctx["sid"], ctx["ext"]["extension"]
    entries = ctx["entries"]
    b = f"gen/binutils/out/{sid}"
    defs = "".join(_defines(e) for e in entries)
    decls = "".join(_declare(e) for e in entries)
    ents = "".join(_entry(e, ext) for e in entries)
    opc_h = _head(ctx, f"{ext}: definitions inserted into include/opcode/riscv-opc.h.") + defs + decls
    opc_c = _head(ctx, f"{ext}: entries inserted into opcodes/riscv-opc.c.") + ents
    src, dump = [".text", "target:"], []
    addr = 0
    for e in entries:
        for line, word, dis in _cases(e):
            src.append(line)
            dump.append(f"[ \t]+{addr:x}:[ \t]+{word:08x}[ \t]+{dis}")
            addr += 4
    s = _head(ctx, f"gas test for {ext}: every mnemonic.", "#") + "\n".join(src) + "\n"
    d = (_head(ctx, f"gas dump test for {ext}.", "#").replace("slice_sha256: ", "slice sha256 ") +
         f"#as: -march=rv64i_{ext}1p0\n#source: x-{ext}.s\n#objdump: -d\n\n"
         ".*:[ \t]+file format .*\n\n\nDisassembly of section .text:\n\n0+000 <target>:\n" + "\n".join(dump) + "\n")
    U = ext.upper()
    patches = {
        "_notice": "© 1993–2026 Abhishek Choudhary. All rights reserved. AyeAI. SPDX-License-Identifier: CC0-1.0",
        "generator": GENERATOR, "spec": sid, "version": ctx["version"], "slice_sha256": ctx["slice_sha256"],
        "extension": ext,
        "copy": [{"from": f"{b}/gas", "to": "gas/testsuite/gas/riscv", "pattern": "*", "rename_prefix": "x-"}],
        "anchors": [
            {"file": "include/opcode/riscv.h", "where": "after", "anchor": "  INSN_CLASS_XVENTANACONDOPS,\n",
             "text": f"  INSN_CLASS_{U},\n"},
            {"file": "include/opcode/riscv-opc.h", "where": "after", "anchor": "#define MASK_VT_MASKCN 0xfe00707f\n",
             "text": f"/* {ext} (repsynth) */\n" + defs},
            {"file": "include/opcode/riscv-opc.h", "where": "after",
             "anchor": "DECLARE_INSN(vt_maskcn, MATCH_VT_MASKCN, MASK_VT_MASKCN)\n", "text": decls},
            {"file": "opcodes/riscv-opc.c", "where": "after",
             "anchor": "{\"vt.maskcn\",  64, INSN_CLASS_XVENTANACONDOPS, \"d,s,t\", MATCH_VT_MASKCN, MASK_VT_MASKCN, match_opcode, 0 },\n",
             "text": f"\n/* {ext} (repsynth) */\n" + ents},
            {"file": "bfd/elfxx-riscv.c", "where": "after",
             "anchor": "  {\"xventanacondops\",\tISA_SPEC_CLASS_DRAFT,\t1, 0, 0 },\n",
             "text": f"  {{\"{ext}\",\t\tISA_SPEC_CLASS_DRAFT,\t1, 0, 0 }},\n"},
            {"file": "bfd/elfxx-riscv.c", "where": "after",
             "anchor": "    case INSN_CLASS_XVENTANACONDOPS:\n      return riscv_subset_supports (rps, \"xventanacondops\");\n",
             "text": f"    case INSN_CLASS_{U}:\n      return riscv_subset_supports (rps, \"{ext}\");\n"},
            {"file": "bfd/elfxx-riscv.c", "where": "after",
             "anchor": "    case INSN_CLASS_XVENTANACONDOPS:\n      return \"xventanacondops\";\n",
             "text": f"    case INSN_CLASS_{U}:\n      return \"{ext}\";\n"},
            {"file": "gas/testsuite/gas/riscv/march-help.l", "where": "after",
             "anchor": "\txventanacondops                         1.0\n", "text": f"\t{ext:<40}1.0\n"},
        ],
    }
    return {f"{b}/{ext}-opc.h": opc_h, f"{b}/{ext}-opc.c": opc_c, f"{b}/gas/{ext}.s": s, f"{b}/gas/{ext}.d": d,
            f"{b}/patches.json": json.dumps(patches, indent=2, ensure_ascii=False) + "\n"}
